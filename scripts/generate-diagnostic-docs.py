#!/usr/bin/env python3
"""Generate the runtime explanation catalog and bilingual reference from one reviewed source."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "eng/diagnostics/catalog.json"
CODE = re.compile(r"(?:BGCS(?:-[A-Z0-9]+)+|BGCS(?:CS|CPP|IO)[0-9]{3}|BGCSCPP-INSTANTIATION)\Z")


def rows() -> list[dict]:
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    if data.get("schemaVersion") != 1 or not data.get("diagnostics"):
        raise RuntimeError("The diagnostic catalog requires its supported revision and a nonempty collection.")
    values = data["diagnostics"]
    if len({value["code"] for value in values}) != len(values):
        raise RuntimeError("Diagnostic IDs must be unique.")
    for value in values:
        if not CODE.fullmatch(value["code"]):
            raise RuntimeError("Invalid diagnostic ID: " + value["code"])
        for text in [value[key] for key in ("title", "cause", "resolution")] + [value["zh"][key] for key in ("title", "cause", "resolution")]:
            if not isinstance(text, str) or not text.strip() or "\n" in text or "\r" in text:
                raise RuntimeError("Each diagnostic requires complete single-paragraph English and Chinese text.")
    return sorted(values, key=lambda value: value["code"])


def outputs(values: list[dict]) -> dict[Path, str]:
    source = ["// <auto-generated/>", "// Source: eng/diagnostics/catalog.json; regenerate with scripts/generate-diagnostic-docs.py.",
              "namespace BGCS.Contracts;", "", "/// <summary>Defines the generated diagnostic explanations from the reviewed bilingual catalog.</summary>",
              "public static partial class BindingDiagnosticCatalog", "{",
              "    private static BindingDiagnosticDescriptor[] CreateDescriptors() =>", "    ["]
    for value in values:
        arguments = [json.dumps(value[key], ensure_ascii=False) for key in ("code", "title", "cause", "resolution")]
        source.append("        new(" + arguments[0] + ",")
        source.extend("            " + argument + "," for argument in arguments[1:-1])
        source.append("            " + arguments[-1] + "),")
    source += ["    ];", "}", ""]
    result = {ROOT / "src/BGCS.Contracts/BindingDiagnosticCatalog.Generated.cs": "\n".join(source)}
    for language in ("en", "zh"):
        chinese = language == "zh"
        lines = ["# BGCS 诊断参考" if chinese else "# BGCS diagnostic reference", "",
                 "<!-- Generated from eng/diagnostics/catalog.json; edit that source and regenerate. -->", "",
                 "`bindgen-cs explain CODE` 显示同一目录中的英文原因与处理方法。具体诊断消息、源码位置和阶段提供本次失败的上下文。" if chinese else
                 "`bindgen-cs explain CODE` exposes the same catalog's English cause and resolution. The individual message, source location and stage provide the current failure context.", ""]
        for value in values:
            text = value["zh"] if chinese else value
            lines += ["## " + value["code"] + " — " + text["title"], "",
                      ("原因：" if chinese else "Cause: ") + text["cause"], "",
                      ("处理：" if chinese else "Resolution: ") + text["resolution"], ""]
        result[ROOT / "docs/generated" / ("diagnostic-reference.cn.md" if chinese else "diagnostic-reference.md")] = "\n".join(lines)
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    values = rows()
    known = {value["code"] for value in values}
    missing = {}
    for directory in (ROOT / "src", ROOT / "integrations"):
        for path in directory.rglob("*.cs"):
            if {"bin", "obj"}.intersection(path.relative_to(ROOT).parts):
                continue
            for literal in re.findall(r'"(BGCS[A-Z0-9-]*)"', path.read_text(encoding="utf-8-sig")):
                if CODE.fullmatch(literal) and literal not in known:
                    missing.setdefault(literal, []).append(path.relative_to(ROOT).as_posix())
    if missing:
        raise RuntimeError("Emitted diagnostic IDs lack reviewed explanations: " + json.dumps(missing, indent=2))
    changed = []
    for path, text in outputs(values).items():
        if path.is_file() and path.read_text(encoding="utf-8-sig") == text:
            continue
        changed.append(path.relative_to(ROOT).as_posix())
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if args.check and changed:
        raise RuntimeError("Generated diagnostic catalog/reference files are stale: " + ", ".join(changed))
    print("[diagnostics] " + str(len(values)) + " reviewed explanations; production code coverage and generated references match.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
