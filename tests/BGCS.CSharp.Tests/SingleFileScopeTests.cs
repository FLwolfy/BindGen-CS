using System;
using System.IO;
using System.Linq;
using BGCS.CSharp.Emission;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace BGCS.CSharp.Tests;

public sealed class SingleFileScopeTests
{
    [Fact]
    public void NullableAnnotationsKeepTheirEnabledContextAfterComposition()
    {
        string source = new SingleFileComposer().ComposeSources([
            ("input.cs", "#nullable enable\nnamespace Generated { public sealed class Value { public object? Item { get; set; } } }")], "Generated");

        Assert.Contains("#nullable enable", source, StringComparison.Ordinal);
        CSharpCompilation compilation = Compile(source);
        INamedTypeSymbol type = compilation.GetTypeByMetadataName("Generated.Value")!;
        Assert.Equal(NullableAnnotation.Annotated,
            ((IPropertySymbol)Assert.Single(type.GetMembers("Item"))).Type.NullableAnnotation);
    }

    [Fact]
    public void HeaderTargetAndNestedDeclarationsRetainDeterministicIndentation()
    {
        string source = new SingleFileComposer().ComposeSources([
            ("input.cs", "namespace Generated { public class Value { public int Get() { return 1; } } }")],
            "Generated", "macos-arm64-darwin");

        Assert.Contains("//     This code was generated by BindGen-CS.\n" +
            "//     ABI reference target: macos-arm64-darwin\n" +
            "//     Changes will be replaced", source.Replace("\r\n", "\n", StringComparison.Ordinal), StringComparison.Ordinal);
        Assert.Matches(@"(?m)^    public class Value\r?$", source);
        Assert.Matches(@"(?m)^        public int Get\(\)\r?$", source);
        Assert.Matches(@"(?m)^            return 1;\r?$", source);
        Assert.NotNull(Compile(source).GetTypeByMetadataName("Generated.Value"));
    }

    [Fact]
    public void NamespaceAliases_KeepTheirOriginalScopesAcrossPartialDeclarations()
    {
        string source = new SingleFileComposer().ComposeSources([
            ("first.cs", "namespace Example { using Value = global::System.Int32; public partial class Api { public Value First; } }"),
            ("second.cs", "namespace Example { using Value = global::System.Int64; public partial class Api { public Value Second; } }"),
            ("runtime.cs", "namespace Example.Runtime; public class Helper {}")], "Example");
        var compilation = CSharpCompilation.Create("SingleFileScopes", [CSharpSyntaxTree.ParseText(source)],
            ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
                .Distinct(StringComparer.OrdinalIgnoreCase).Select(path => MetadataReference.CreateFromFile(path)),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        Assert.DoesNotContain(compilation.GetDiagnostics(), diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);
        INamedTypeSymbol type = compilation.GetTypeByMetadataName("Example.Api")!;
        Assert.Equal(SpecialType.System_Int32, ((IFieldSymbol)Assert.Single(type.GetMembers("First"))).Type.SpecialType);
        Assert.Equal(SpecialType.System_Int64, ((IFieldSymbol)Assert.Single(type.GetMembers("Second"))).Type.SpecialType);
        Assert.NotNull(compilation.GetTypeByMetadataName("Example.Runtime.Helper"));
    }

    private static CSharpCompilation Compile(string source)
    {
        CSharpCompilation compilation = CSharpCompilation.Create("ComposedSource", [CSharpSyntaxTree.ParseText(source)],
            ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
                .Distinct(StringComparer.OrdinalIgnoreCase).Select(path => MetadataReference.CreateFromFile(path)),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, generalDiagnosticOption: ReportDiagnostic.Error));
        using MemoryStream image = new();
        var result = compilation.Emit(image);
        Assert.True(result.Success, string.Join(Environment.NewLine, result.Diagnostics));
        return compilation;
    }
}
