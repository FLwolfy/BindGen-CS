using System;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Threading;
using BGCS.Analysis.Types;
using BGCS.Contracts.Artifacts;
using BGCS.Contracts.Bridge;
using BGCS.Contracts.Common;
using BGCS.Contracts.Native;

namespace BGCS.Cpp2C.Emission;

/// <summary>Emits exact C adapters for source helpers whose original names are not guaranteed native exports.</summary>
public sealed class CHeaderBridgeEmitter
{
    /// <summary>Writes a public helper header and C implementation; both belong to the configured native module.</summary>
    /// <param name="module">The immutable helper export plan.</param>
    /// <param name="source">The original detached C types.</param>
    /// <param name="headers">The original native input headers, already relocated for the generated header directory.</param>
    /// <param name="sink">The owned native candidate sink.</param>
    /// <param name="preamble">The original parse preamble.</param>
    /// <param name="postamble">The original parse postamble.</param>
    /// <param name="cancellationToken">Cancels emission before publication.</param>
    /// <returns>The complete generated helper artifacts.</returns>
    public ImmutableArray<ArtifactDescriptor> Emit(
        CHeaderBridgeModule module,
        NativeModule source,
        ImmutableArray<string> headers,
        IArtifactSink sink,
        string preamble = "",
        string postamble = "",
        CancellationToken cancellationToken = default
    ) {
        ArgumentNullException.ThrowIfNull(module);
        ArgumentNullException.ThrowIfNull(source);
        ArgumentNullException.ThrowIfNull(sink);
        if (module.exports.IsEmpty) return [];
        CHeaderBridgeModule checkedPlan = new BGCS.Analysis.Bridge.CHeaderBridgePlanner().Plan(source, module.exports.Select(export => export.sourceDeclaration), module.exportPrefix);
        if (!checkedPlan.exports.Select(Identity).SequenceEqual(module.exports.Select(Identity), StringComparer.Ordinal))
            throw new InvalidOperationException("A C header adapter plan no longer matches its original callable facts.");
        string stem = module.exportPrefix + "_helpers";
        string macro = module.exportPrefix.TrimEnd('_').ToUpperInvariant() + "_HEADER_HELPER";
        string api = macro + "_EXPORT", call = macro + "_CALL";
        StringBuilder header = new("/* Generated by BGCS. Compile the matching C adapter into the configured native module. */\n#pragma once\n");
        header.Append(preamble).Append('\n');
        foreach (string path in headers)
        {
            if (path.Any(character => character is '\r' or '\n' or '"' or '\0')) throw new ArgumentException("A C helper header input cannot be represented as a quoted include.", nameof(headers));
            header.Append("#include \"").Append(path.Replace('\\', '/')).AppendLine("\"");
        }
        header.Append(postamble).Append("\n#if defined(_WIN32)\n#define ").Append(api).Append(" __declspec(dllexport)\n#define ").Append(call)
            .Append(" __cdecl\n#else\n#define ").Append(api).Append(" __attribute__((visibility(\"default\")))\n#define ").Append(call).Append('\n').AppendLine("#endif");
        StringBuilder implementation = new("/* Generated by BGCS. This C source must be linked into the configured native module. */\n#include \"../include/");
        implementation.Append(stem).AppendLine(".h\"");
        NativeTypeFormatter formatter = new();
        foreach (CHeaderBridgeExport export in module.exports)
        {
            cancellationToken.ThrowIfCancellationRequested();
            string arguments = string.Join(", ", export.parameters.Select((
                parameter,
                index
            ) => formatter.FormatDeclaration(source, parameter.type, "bgcs_argument" + index.ToString(CultureInfo.InvariantCulture))));
            if (arguments.Length == 0) arguments = "void";
            string signature = api + " " + formatter.FormatDeclaration(source, export.returnType, call + " " + export.exportName + "(" + arguments + ")");
            header.Append(signature).AppendLine(";");
            implementation.Append(signature).AppendLine(" {");
            NativeType result = source.GetType(export.returnType);
            while (result.category is NativeTypeCategory.Alias or NativeTypeCategory.Qualified) result = source.GetType(result.elementType!.Value);
            implementation.Append("    ").Append(result.primitiveKind == "Void" ? string.Empty : "return ").Append(export.sourceName).Append('(')
                .Append(string.Join(", ", export.parameters.Select((
                    _,
                    index
                ) => "bgcs_argument" + index.ToString(CultureInfo.InvariantCulture)))).AppendLine(");\n}");
        }
        return [Write("include/" + stem + ".h", "text/x-c-header", header.ToString()), Write("src/" + stem + ".c", "text/x-c", implementation.ToString())];

        ArtifactDescriptor Write(
            string path,
            string mediaType,
            string text
        ) {
            cancellationToken.ThrowIfCancellationRequested();
            sink.WriteText(path, text);
            return new(path, mediaType, new ContentDigest(Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)))));
        }
        static string Identity(CHeaderBridgeExport export) => export.sourceDeclaration.value + "|" + export.sourceName + "|" + export.exportName + "|" + export.returnType.value
            + "|" + string.Join("|", export.parameters.Select(parameter => parameter.sourceDeclaration.value + ":" + parameter.type.value));
    }
}
