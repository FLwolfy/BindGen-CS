using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Threading;
using BGCS.Analysis.Bridge;
using BGCS.Analysis.Types;
using BGCS.Core.Artifacts;
using BGCS.Core.Bridge;
using BGCS.Core.Common;
using BGCS.Core.Native;

namespace BGCS.NativeBridge.Emission;

internal sealed class CBridgeEmitter
{
    internal ImmutableArray<ArtifactDescriptor> Emit(
        NativeBridgePlan plan,
        IArtifactSink sink,
        string stem,
        CancellationToken cancellationToken
    ) {
        if (string.IsNullOrWhiteSpace(stem) || stem.Any(c => !char.IsAsciiLetterOrDigit(c) && c is not '_' and not '-'))
            throw new ArgumentException("A native source stem must be a portable file identifier.", nameof(stem));
        new CBridgeOperationVerifier().Verify(plan);
        Dictionary<StableId, BridgeType> types = plan.types.ToDictionary(type => type.id);
        NativeTypeFormatter formatter = new();
        ControlledSourceFragmentVerifier fragments = new();
        string decoration = plan.sourceConventions?.exportDecoration
            ?? throw new InvalidOperationException("Native source export conventions were not supplied by the target extension.");
        string calling = plan.sourceConventions.cdeclDecoration;
        StringBuilder header = new("/* Generated by BGCS. Compile the matching source in the declared binding module. */\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n");
        header.Append(plan.preamble).Append('\n');
        foreach (string path in plan.headers)
        {
            if (path.Any(c => c is '\r' or '\n' or '"' or '\0')) throw new InvalidOperationException("A native input cannot be quoted as an include.");
            header.Append("#include \"").Append(path.Replace('\\', '/')).AppendLine("\"");
        }
        header.Append(plan.postamble).Append("\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
        foreach (BridgeType handle in plan.types.Where(type => type.kind == BridgeTypeKind.Handle))
            header.Append("typedef struct ").Append(handle.cName).Append("* ").Append(handle.cName).AppendLine(";");
        foreach (BridgeType enumeration in plan.types.Where(type => type.kind == BridgeTypeKind.Enumeration))
            header.Append("typedef ").Append(Declare(types[enumeration.elementType!.Value], enumeration.cName)).AppendLine(";");
        foreach (BridgeType callback in types.Values.Where(type => type.kind == BridgeTypeKind.Function).OrderBy(type => type.cName, StringComparer.Ordinal))
            header.Append("typedef ").Append(Declare(types[callback.returnType!.Value],
                "(" + calling + " " + callback.cName + ")(" + Arguments(callback.parameterTypes.Select((
                    id,
                    index
                ) => Declare(types[id], "value" + index))) + ")")).AppendLine(";");
        foreach (BridgeExport export in plan.exports)
        {
            cancellationToken.ThrowIfCancellationRequested();
            header.Append(Signature(export)).AppendLine(";");
        }
        header.Append("#ifdef __cplusplus\n}\n#endif\n");
        StringBuilder source = new("/* Generated by BGCS. */\n#include \"../include/");
        source.Append(stem).AppendLine(".h\"").AppendLine("#include <stdlib.h>");
        foreach (ControlledSourceFragment fragment in plan.sourceFragments) source.Append(fragment.text).Append('\n');
        foreach (BridgeExport export in plan.exports)
        {
            AggregateCallbackAdapter[] adapters = Adapters(export);
            NativeCallbackContextPlan? retained = plan.callbackContexts.SingleOrDefault(context => context.registrationFunction == export.operation.declaration);
            foreach (var group in adapters.GroupBy(adapter => adapter.userDataParameter))
            {
                string context = ContextName(export, group.Key, retained);
                source.Append("struct ").Append(context).AppendLine(" {").AppendLine("    void* user_data;");
                if (retained is not null) source.Append("    ").Append(formatter.FormatDeclaration(plan.source, retained.nativeHandleType, "native_handle")).AppendLine(";");
                foreach (AggregateCallbackAdapter adapter in group)
                    source.Append("    ").Append(Declare(types[adapter.carrierType], "*" + CallbackField(adapter))).AppendLine(";");
                source.AppendLine("};");
                foreach (AggregateCallbackAdapter adapter in group) EmitThunk(export, adapter, context);
            }
        }
        foreach (BridgeExport export in plan.exports)
        {
            cancellationToken.ThrowIfCancellationRequested();
            NativeDeclaration callable = plan.source.GetDeclaration(export.operation.declaration!.Value);
            NativeDeclaration[] original = callable.children.Select(plan.source.GetDeclaration).Where(item => item.kind == "Parameter").ToArray();
            AggregateCallbackAdapter[] adapters = Adapters(export);
            NativeCallbackContextPlan? retained = plan.callbackContexts.SingleOrDefault(context => context.registrationFunction == callable.id);
            NativeCallbackContextPlan? shutdown = plan.callbackContexts.SingleOrDefault(context => context.unregisterFunction == callable.id);
            NativeCallbackContextPlan? cancellation = plan.callbackContexts.SingleOrDefault(context => context.cancelFunction == callable.id);
            var groups = adapters.GroupBy(adapter => adapter.userDataParameter).ToArray();
            source.Append(Signature(export)).AppendLine(" {");
            foreach (var group in groups)
            {
                string context = ContextName(export, group.Key, retained);
                BridgeParameter data = ParameterFor(export, group.Key);
                string state = StateName(group.Key);
                if (retained is null) source.Append("    struct ").Append(context).Append(' ').Append(state).AppendLine(";");
                else source.Append("    struct ").Append(context).Append("* ").Append(state).Append(" = malloc(sizeof(*").Append(state).AppendLine("));")
                    .Append("    if (").Append(state).AppendLine(" == NULL) return NULL;");
                string access = state + (retained is null ? "." : "->");
                source.Append("    ").Append(access).Append("user_data = (void*)").Append(data.name).AppendLine(";");
                foreach (AggregateCallbackAdapter adapter in group)
                    source.Append("    ").Append(access).Append(CallbackField(adapter)).Append(" = ").Append(ParameterFor(export, adapter.sourceParameter).name).AppendLine(";");
            }
            NativeCallbackContextPlan? borrowed = shutdown ?? cancellation;
            string? handleParameter = borrowed is null ? null : ParameterFor(export,
                shutdown is not null ? borrowed.unregisterHandleParameter : borrowed.cancellationHandleParameter!.Value).name;
            NativeVariadicAdapter? finite = export.operation.finiteVariadic;
            string invocation = (finite?.wrapper ?? callable.name) + "(" + string.Join(", ", original.Select((
                parameter,
                index
            ) => Argument(parameter, index))
                .Concat(finite is null ? [] : export.parameters.Skip(original.Length).Select(Convert))) + ")";
            if (export.operation.invocationExpression is ControlledSourceFragment wrapped)
                invocation = "(" + fragments.Substitute(wrapped, new Dictionary<string, string>(StringComparer.Ordinal) { ["invocation"] = invocation }) + ")";
            if (retained is not null)
            {
                string state = StateName(adapters[0].userDataParameter);
                source.Append("    ").Append(state).Append("->native_handle = ").Append(invocation).AppendLine(";")
                    .Append("    if (").Append(state).AppendLine("->native_handle == NULL) {")
                    .Append("        free(").Append(state).AppendLine(");\n        return NULL;\n    }")
                    .Append("    return ").Append(state).AppendLine(";");
            }
            else
            {
                if (export.resultType is null)
                {
                    source.Append("    ").Append(invocation).AppendLine(";");
                    if (shutdown is not null) source.Append("    free(").Append(handleParameter).AppendLine(");");
                }
                else
                {
                    source.Append("    ").Append(formatter.FormatDeclaration(plan.source, callable.returnType!.Value, "bgcs_native_value"))
                        .Append(" = ").Append(invocation).AppendLine(";");
                    if (shutdown is not null) source.Append("    free(").Append(handleParameter).AppendLine(");");
                    string value = Result(export, "bgcs_native_value");
                    source.Append(export.resultInOutputParameter ? "    *bgcs_result = " : "    return ").Append(value).AppendLine(";");
                }
            }
            source.AppendLine("}");

            string Argument(
                NativeDeclaration parameter,
                int index
            ) {
                AggregateCallbackAdapter? adapter = adapters.SingleOrDefault(item => item.sourceParameter == parameter.id);
                if (adapter is not null) return ParameterFor(export, parameter.id).name + " == NULL ? NULL : " + ThunkName(export, adapter);
                if (groups.Any(group => group.Key == parameter.id)) return "(void*)" + (retained is null ? "&" : string.Empty) + StateName(parameter.id);
                if (borrowed is not null && parameter.id == (shutdown is not null ? borrowed.unregisterHandleParameter : borrowed.cancellationHandleParameter))
                    return "(" + formatter.FormatDeclaration(plan.source, parameter.type!.Value, string.Empty) + ")" + handleParameter + "->native_handle";
                if (!export.operation.argumentGroups.IsEmpty)
                {
                    BridgeArgumentGroup group = export.operation.argumentGroups[index];
                    if (group.expression is not null)
                    {
                        Dictionary<string, string> values = group.inputs.ToDictionary(input => input.name,
                            input => export.parameters.Single(value => value.id == input.parameter).name, StringComparer.Ordinal);
                        values.Add("nativeType", formatter.FormatDeclaration(plan.source, group.nativeType, string.Empty));
                        return "(" + fragments.Substitute(group.expression, values) + ")";
                    }
                    return Convert(export.parameters.Single(value => value.id == group.inputs[0].parameter));
                }
                return Convert(export.parameters[index]);
            }
        }
        // Nothing reaches the sink until every typed operation and source expression has been accepted.
        return [Write("include/" + stem + ".h", "text/x-c-header", header.ToString()), Write("src/" + stem + ".c", "text/x-c", source.ToString())];

        string Signature(BridgeExport export)
        {
            IEnumerable<string> arguments = export.parameters.Select(parameter => Declare(types[parameter.type], parameter.name));
            if (export.resultInOutputParameter && export.resultType is StableId result)
                arguments = arguments.Append(Declare(new(new("result-pointer"), BridgeTypeKind.Pointer, string.Empty) { elementType = result }, "bgcs_result"));
            string name = calling + " " + export.name + "(" + Arguments(arguments) + ")";
            return decoration + " " + (export.resultType is StableId direct && !export.resultInOutputParameter ? Declare(types[direct], name) : "void " + name);
        }
        string Declare(
            BridgeType type,
            string name
        ) {
            if (type.kind == BridgeTypeKind.NativeStorage) return formatter.FormatDeclaration(plan.source, type.nativeType!.Value, name);
            if (type.kind == BridgeTypeKind.Function) return type.cName + " " + name;
            if (type.kind == BridgeTypeKind.Pointer)
            {
                BridgeType element = types[type.elementType!.Value];
                bool addConst = type.isConst && !(element.kind == BridgeTypeKind.NativeStorage && TopConst(element.nativeType!.Value));
                return Declare(element, (addConst ? "const *" : "*") + name);
            }
            if (type.kind is BridgeTypeKind.Scalar or BridgeTypeKind.Enumeration or BridgeTypeKind.Handle) return type.cName + " " + name;
            throw new NotSupportedException("A C bridge requires a concrete declared storage type or a registered C representation.");
        }
        bool TopConst(StableId identity)
        {
            HashSet<StableId> visited = [];
            while (true)
            {
                if (!visited.Add(identity)) throw new InvalidOperationException("A C storage qualifier graph is cyclic.");
                NativeType native = plan.source.GetType(identity);
                if (native.qualifier?.Contains("Const", StringComparison.Ordinal) == true) return true;
                if (native.category is not (NativeTypeCategory.Qualified or NativeTypeCategory.Alias) || native.elementType is not StableId nested) return false;
                identity = nested;
            }
        }

        string Convert(BridgeParameter parameter)
        {
            string native = formatter.FormatDeclaration(plan.source, parameter.nativeType!.Value, string.Empty);
            return parameter.conversion switch
            {
                BridgeConversionKind.SourceExpression => "(" + fragments.Substitute(parameter.conversionExpression!, new Dictionary<string, string>(StringComparer.Ordinal)
                { ["value"] = parameter.name, ["nativeType"] = native }) + ")",
                BridgeConversionKind.Dereference => "*" + parameter.name,
                BridgeConversionKind.ScalarCast or BridgeConversionKind.PointerCast when types[parameter.type].kind == BridgeTypeKind.NativeStorage
                    && Resolve(parameter.nativeType!.Value).category == NativeTypeCategory.Record => parameter.name,
                BridgeConversionKind.ScalarCast or BridgeConversionKind.PointerCast => "(" + native + ")" + parameter.name,
                _ => throw new NotSupportedException("The C argument requires an explicit supported typed conversion.")
            };
        }
        string Result(
            BridgeExport export,
            string value
        ) {
            BridgeType type = types[export.resultType!.Value];
            if (export.resultConversion == BridgeConversionKind.SourceExpression)
                return "(" + fragments.Substitute(export.resultExpression!, new Dictionary<string, string>(StringComparer.Ordinal)
                { ["value"] = value, ["resultType"] = Declare(type, string.Empty).Trim() }) + ")";
            return type.kind == BridgeTypeKind.NativeStorage ? value : "(" + Declare(type, string.Empty).Trim() + ")" + value;
        }
        void EmitThunk(
            BridgeExport export,
            AggregateCallbackAdapter adapter,
            string contextName
        ) {
            NativeType function = plan.source.GetType(adapter.sourceCallableType);
            if (function.callingConvention is not ("C" or "Default")) throw new NotSupportedException("The native callback convention requires an explicit callable lowering.");
            string[] original = function.parameterTypes.Select((
                id,
                index
            ) => formatter.FormatDeclaration(plan.source, id, "value" + index)).ToArray();
            source.Append("static ").Append(formatter.FormatDeclaration(plan.source, function.returnType!.Value,
                ThunkName(export, adapter) + "(" + Arguments(original) + ")")).AppendLine(" {")
                .Append("    struct ").Append(contextName).Append("* state = (struct ").Append(contextName).Append("*)value")
                .Append(adapter.callableUserDataIndex).AppendLine(";");
            bool resultOut = Resolve(function.returnType.Value).category == NativeTypeCategory.Record;
            bool isVoid = Resolve(function.returnType.Value).primitiveKind == "Void";
            List<string> arguments = function.parameterTypes.Select((
                id,
                index
            ) => index == adapter.callableUserDataIndex ? "state->user_data"
                : Resolve(id).category == NativeTypeCategory.Record ? "&value" + index : "value" + index).ToList();
            if (resultOut)
            {
                source.AppendLine("    /* Raw callback contract: initialize the complete result on every invocation, including failure paths. */")
                    .Append("    ").Append(formatter.FormatDeclaration(plan.source, Resolve(function.returnType.Value).id, "result")).AppendLine(";");
                arguments.Add("&result");
            }
            source.Append("    ").Append(!resultOut && !isVoid ? "return " : string.Empty).Append("state->")
                .Append(CallbackField(adapter)).Append('(').Append(string.Join(", ", arguments)).AppendLine(");");
            if (resultOut) source.AppendLine("    return result;");
            source.AppendLine("}");
        }
        BridgeParameter ParameterFor(
            BridgeExport export,
            StableId original
        ) {
            NativeDeclaration[] parameters = plan.source.GetDeclaration(export.operation.declaration!.Value).children.Select(plan.source.GetDeclaration).Where(item => item.kind == "Parameter").ToArray();
            if (export.operation.argumentGroups.IsEmpty) return export.parameters[Array.FindIndex(parameters, item => item.id == original)];
            BridgeArgumentGroup group = export.operation.argumentGroups.Single(group => group.sourceParameter == original);
            if (group.inputs.Length != 1 || group.expression is not null) throw new NotSupportedException("Callback state and native handle channels require a dedicated single-carrier callable protocol.");
            return export.parameters.Single(parameter => parameter.id == group.inputs[0].parameter);
        }
        NativeType Resolve(StableId id) => StandardLibraryFactReader.Resolve(plan.source, id);
        AggregateCallbackAdapter[] Adapters(BridgeExport export) => plan.aggregateCallbacks.Where(adapter => adapter.sourceFunction == export.operation.declaration).ToArray();
        string ContextName(
            BridgeExport export,
            StableId data,
            NativeCallbackContextPlan? retained
        )
            => retained is null ? export.name + "_context_" + Digest(data.value) : types[retained.carrierType].cName;
        static string StateName(StableId data) => "bgcs_context_" + Digest(data.value);
        static string Arguments(IEnumerable<string> values) { string result = string.Join(", ", values); return result.Length == 0 ? "void" : result; }
        static string Digest(string value) => System.Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)))[..12];
        static string CallbackField(AggregateCallbackAdapter adapter) => "callback_" + Digest(adapter.sourceParameter.value);
        static string ThunkName(
            BridgeExport export,
            AggregateCallbackAdapter adapter
        ) => export.name + "_" + CallbackField(adapter);
        ArtifactDescriptor Write(
            string path,
            string media,
            string text
        ) {
            cancellationToken.ThrowIfCancellationRequested();
            sink.WriteText(path, text);
            return new(path, media, new(System.Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)))));
        }
    }
}
