    private static bool IsNativeBool(BindingTypeReference type) => string.Equals(type.nativeName.Trim(), "bool", StringComparison.Ordinal) || string.Equals(type.managedName, "Bool8", StringComparison.Ordinal) || string.Equals(type.managedName, "Bool32", StringComparison.Ordinal);
    private static bool IsNativeBoolPointer(BindingTypeReference type)
    {
        if (type.pointerDepth != 1)
            return false;
        string nativeName = type.nativeName.Trim();
        if (!nativeName.EndsWith("*", StringComparison.Ordinal))
            return false;
        nativeName = nativeName[..^1].Replace("const", string.Empty, StringComparison.Ordinal).Replace("volatile", string.Empty, StringComparison.Ordinal).Trim();
        return nativeName is "bool" or "_Bool";
    }

    private static string GetRawManagedName(BindingFunction function) => string.IsNullOrWhiteSpace(function.rawManagedName) ? function.managedName : function.rawManagedName;
    private static FriendlyFunctionPlan CreateFriendlyPlan(BindingFunction function)
    {
        Dictionary<string, int> lengthUseCounts = function.parameters.Where(parameter => parameter.marshalling.strategy is MarshallingStrategy.Pointer or MarshallingStrategy.Span).Select(parameter => parameter.marshalling.lengthParameter).Where(name => !string.IsNullOrWhiteSpace(name)).GroupBy(name => name!, StringComparer.Ordinal).ToDictionary(group => group.Key, group => group.Count(), StringComparer.Ordinal);
        HashSet<string> hiddenLengths = new(StringComparer.Ordinal);
        List<FriendlyParameterPlan> parameters = [];
        foreach (BindingParameter parameter in function.parameters)
        {
            FriendlyParameterKind kind = FriendlyParameterKind.Raw;
            string managedType = parameter.type.managedName;
            string? nativeElementType = GetPointerElementType(parameter.type);
            string? elementType = nativeElementType != null && nativeElementType.EndsWith('*') ? "nint" : nativeElementType;
            string? length = parameter.marshalling.lengthParameter;
            if (parameter.marshalling.strategy == MarshallingStrategy.String && parameter.direction == BindingDirection.In && parameter.marshalling.stringEncoding is BindingStringEncoding.Utf8 or BindingStringEncoding.Utf16)
            {
                kind = FriendlyParameterKind.String;
                managedType = IsNullPointerDefault(parameter.defaultValue) ? "string?" : "string";
            }
            else if (IsNativeBoolPointer(parameter.type) && parameter.direction is BindingDirection.Out or BindingDirection.InOut && !IsNullPointerDefault(parameter.defaultValue))
            {
                kind = FriendlyParameterKind.RefBool;
                managedType = "bool";
                elementType = "bool";
            }
            else if (IsNativeBool(parameter.type))
            {
                kind = FriendlyParameterKind.Bool;
                managedType = "bool";
            }
            else if (elementType != null && !string.Equals(elementType, "void", StringComparison.Ordinal) && parameter.marshalling.strategy is MarshallingStrategy.Pointer or MarshallingStrategy.Span && !string.IsNullOrWhiteSpace(length) && lengthUseCounts.ContainsKey(length))
            {
                kind = FriendlyParameterKind.Span;
                managedType = parameter.direction == BindingDirection.In ? $"ReadOnlySpan<{elementType}>" : $"Span<{elementType}>";
                hiddenLengths.Add(length);
            }
            else if (elementType != null && !string.Equals(elementType, "void", StringComparison.Ordinal) && parameter.type.pointerDepth == 1 && parameter.marshalling.strategy == MarshallingStrategy.Pointer && parameter.direction is BindingDirection.Out or BindingDirection.InOut && !IsNullPointerDefault(parameter.defaultValue))
            {
                kind = parameter.direction == BindingDirection.Out ? FriendlyParameterKind.Out : FriendlyParameterKind.Ref;
                managedType = elementType;
            }

            parameters.Add(new(parameter, kind, managedType, elementType));
        }

        foreach (BindingParameter parameter in function.parameters)
        {
            if (hiddenLengths.Contains(parameter.nativeName) || hiddenLengths.Contains(parameter.managedName))
                parameters.RemoveAll(plan => ReferenceEquals(plan.parameter, parameter));
        }

        bool returnsString = function.returnMarshalling.strategy == MarshallingStrategy.String && function.returnMarshalling.stringEncoding is BindingStringEncoding.Utf8 or BindingStringEncoding.Utf16 && function.returnType.pointerDepth > 0;
        bool returnsBool = IsNativeBool(function.returnType);
        return new(parameters, hiddenLengths, returnsString, returnsBool, null);
    }

    private static bool IsNullPointerDefault(string? value) => value?.Trim() is "NULL" or "nullptr" or "default";
    private static void EmitFriendlyManagedFunction(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        FriendlyFunctionPlan plan,
        string nativeOwner
    ) {
        writer.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
        writer.Append("        public static ").Append(GetFriendlyReturnType(function, plan)).Append(' ').Append(function.managedName).Append('(');
        for (int index = 0; index < plan.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            FriendlyParameterPlan parameter = plan.parameters[index];
            if (function.managedKind == BindingManagedFunctionKind.Extension && function.managedReceiverIndex == function.parameters.IndexOf(parameter.parameter))
                writer.Append("this ");
            if (parameter.kind == FriendlyParameterKind.Out)
                writer.Append("out ");
            else if (parameter.kind is FriendlyParameterKind.Ref or FriendlyParameterKind.RefBool)
                writer.Append("ref ");
            writer.Append(parameter.managedType).Append(' ').Append(parameter.parameter.managedName);
        }

        writer.AppendLine(")");
        writer.AppendLine("        {");
        List<FriendlyParameterPlan> strings = plan.parameters.Where(parameter => parameter.kind == FriendlyParameterKind.String).ToList();
        foreach (FriendlyParameterPlan parameter in strings)
            writer.Append("            nint ").Append(GetTemporaryName(parameter.parameter)).AppendLine(" = 0;");
        foreach (FriendlyParameterPlan parameter in plan.parameters.Where(parameter => parameter.kind == FriendlyParameterKind.Out))
            writer.Append("            ").Append(parameter.parameter.managedName).AppendLine(" = default;");
        if (strings.Count > 0)
        {
            writer.AppendLine("            try");
            writer.AppendLine("            {");
            foreach (FriendlyParameterPlan parameter in strings)
            {
                string allocator = parameter.parameter.marshalling.stringEncoding == BindingStringEncoding.Utf16 ? "StringToCoTaskMemUni" : "StringToCoTaskMemUTF8";
                writer.Append("                ").Append(GetTemporaryName(parameter.parameter)).Append(" = ").Append(parameter.parameter.managedName).Append(" is null ? 0 : Marshal.").Append(allocator).Append('(').Append(parameter.parameter.managedName).AppendLine(");");
            }
        }

        int baseIndent = strings.Count > 0 ? 4 : 3;
        List<FriendlyParameterPlan> fixedParameters = plan.parameters.Where(parameter => parameter.kind is FriendlyParameterKind.Span or FriendlyParameterKind.Ref or FriendlyParameterKind.Out or FriendlyParameterKind.RefBool).ToList();
        foreach (FriendlyParameterPlan parameter in fixedParameters)
        {
            AppendIndent(writer, baseIndent);
            writer.Append("fixed (").Append(parameter.elementType).Append("* ").Append(GetTemporaryName(parameter.parameter)).Append(" = ");
            if (parameter.kind == FriendlyParameterKind.Span)
                writer.Append(parameter.parameter.managedName);
            else
                writer.Append('&').Append(parameter.parameter.managedName);
            writer.AppendLine(")");
            AppendIndent(writer, baseIndent);
            writer.AppendLine("{");
            baseIndent++;
        }

        AppendIndent(writer, baseIndent);
        if (plan.returnsString)
            writer.Append("var nativeResult = ");
        else if (plan.returnsBool)
            writer.Append(function.returnType.managedName).Append(" ret = ");
        else if (!string.Equals(function.returnType.managedName, "void", StringComparison.Ordinal))
        {
            if (plan.returnTypeOverride == null)
                writer.Append("return ");
            else
                writer.Append(function.returnType.managedName).Append(" ret = ");
        }

        writer.Append(nativeOwner).Append(GetRawManagedName(function)).Append("Native(");
        bool firstArgument = true;
        for (int index = 0; index < function.parameters.Count; index++)
        {
            BindingParameter nativeParameter = function.parameters[index];
            FriendlyParameterPlan? parameter = plan.parameters.FirstOrDefault(candidate => ReferenceEquals(candidate.parameter, nativeParameter));
            if (!firstArgument)
                writer.Append(", ");
            firstArgument = false;
            if (parameter != null)
            {
                writer.Append(parameter.kind switch
                {
                    FriendlyParameterKind.String => $"({nativeParameter.type.managedName}){GetTemporaryName(nativeParameter)}",
                    FriendlyParameterKind.Span or FriendlyParameterKind.Ref or FriendlyParameterKind.Out or FriendlyParameterKind.RefBool => $"({nativeParameter.type.managedName}){GetTemporaryName(nativeParameter)}",
                    FriendlyParameterKind.PointerHandle => $"({nativeParameter.type.managedName}){nativeParameter.managedName}.Handle",
                    FriendlyParameterKind.Bool => $"{nativeParameter.managedName} ? ({nativeParameter.type.managedName})1 : ({nativeParameter.type.managedName})0",
                    _ => nativeParameter.managedName
                });
                continue;
            }

            FriendlyParameterPlan? owner = plan.parameters.FirstOrDefault(candidate => candidate.kind == FriendlyParameterKind.Span && (string.Equals(candidate.parameter.marshalling.lengthParameter, nativeParameter.managedName, StringComparison.Ordinal) || string.Equals(candidate.parameter.marshalling.lengthParameter, nativeParameter.nativeName, StringComparison.Ordinal)));
            writer.Append(owner == null ? nativeParameter.managedName : $"({nativeParameter.type.managedName}){owner.parameter.managedName}.Length");
        }

        writer.AppendLine(");");
        if (plan.returnsString)
        {
            string converter = function.returnMarshalling.stringEncoding == BindingStringEncoding.Utf16 ? "PtrToStringUni" : "PtrToStringUTF8";
            BindingFunction? cleanup = string.IsNullOrWhiteSpace(function.returnMarshalling.cleanupFunction) ? null : module.functions.FirstOrDefault(candidate => string.Equals(candidate.nativeName, function.returnMarshalling.cleanupFunction, StringComparison.Ordinal));
            if (cleanup == null)
            {
                AppendIndent(writer, baseIndent);
                writer.Append("return (nint)nativeResult == 0 ? null : Marshal.").Append(converter).AppendLine("((nint)nativeResult);");
            }
            else
            {
                AppendIndent(writer, baseIndent);
                writer.AppendLine("try");
                AppendIndent(writer, baseIndent);
                writer.AppendLine("{");
                AppendIndent(writer, baseIndent + 1);
                writer.Append("return (nint)nativeResult == 0 ? null : Marshal.").Append(converter).AppendLine("((nint)nativeResult);");
                AppendIndent(writer, baseIndent);
                writer.AppendLine("}");
                AppendIndent(writer, baseIndent);
                writer.AppendLine("finally");
                AppendIndent(writer, baseIndent);
                writer.AppendLine("{");
                AppendIndent(writer, baseIndent + 1);
                string cleanupOwner = string.Equals(cleanup.managedContainer, function.managedContainer, StringComparison.Ordinal) ? nativeOwner : module.name + ".";
                writer.Append(cleanupOwner).Append(GetRawManagedName(cleanup)).Append("Native((").Append(cleanup.parameters[0].type.managedName).AppendLine(")nativeResult);");
                AppendIndent(writer, baseIndent);
                writer.AppendLine("}");
            }
        }
        else if (plan.returnsBool)
        {
            AppendIndent(writer, baseIndent);
            writer.AppendLine("return ret != 0;");
        }
        else if (plan.returnTypeOverride != null)
        {
            AppendIndent(writer, baseIndent);
            writer.Append("return new ").Append(plan.returnTypeOverride).AppendLine("(ret);");
        }

        for (int index = fixedParameters.Count - 1; index >= 0; index--)
        {
            baseIndent--;
            AppendIndent(writer, baseIndent);
            writer.AppendLine("}");
        }

        if (strings.Count > 0)
        {
            writer.AppendLine("            }");
            writer.AppendLine("            finally");
            writer.AppendLine("            {");
            foreach (FriendlyParameterPlan parameter in strings)
            {
                string temporaryName = GetTemporaryName(parameter.parameter);
                writer.Append("                if (").Append(temporaryName).Append(" != 0) Marshal.FreeCoTaskMem(").Append(temporaryName).AppendLine(");");
            }

            writer.AppendLine("            }");
        }

        writer.AppendLine("        }");
    }

    private static string? GetPointerElementType(BindingTypeReference type)
    {
        if (type.pointerDepth <= 0 || !type.managedName.EndsWith('*'))
            return null;
        return type.managedName[..^1].TrimEnd();
    }

    private static string GetTemporaryName(BindingParameter parameter) => "p_" + parameter.managedName.TrimStart('@');
    private static void AppendIndent(
        StringBuilder writer,
        int levels
    ) => writer.Append(' ', levels * 4);
    private enum FriendlyParameterKind
    {
        Raw,
        String,
        Span,
        Ref,
        Out,
        Bool,
        RefBool,
        PointerHandle
    }

    private sealed record FriendlyParameterPlan(
        BindingParameter parameter,
        FriendlyParameterKind kind,
        string managedType,
        string? elementType
    );
    private sealed record FriendlyFunctionPlan(
        IReadOnlyList<FriendlyParameterPlan> parameters,
        IReadOnlySet<string> hiddenLengths,
        bool returnsString,
        bool returnsBool,
        string? returnTypeOverride
    )
    {
        public bool hasParameterTransform => this.parameters.Any(parameter => parameter.kind != FriendlyParameterKind.Raw) || this.hiddenLengths.Count > 0;
        public bool hasTransform => this.hasParameterTransform || this.returnsString || this.returnsBool || this.returnTypeOverride != null;
        public bool hasNonPointerHandleParameterTransform => this.parameters.Any(parameter => parameter.kind is not FriendlyParameterKind.Raw and not FriendlyParameterKind.PointerHandle) || this.hiddenLengths.Count > 0;
        public bool hasNonPointerHandleTransform => this.hasNonPointerHandleParameterTransform || this.returnsString || this.returnsBool;
    }

    private static string GetFriendlyReturnType(
        BindingFunction function,
        FriendlyFunctionPlan plan
    ) => plan.returnsString ? "string?" : plan.returnsBool ? "bool" : plan.returnTypeOverride ?? function.returnType.managedName;
    private static void EmitExternFunction(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        string modifiers
    ) {
        bool hasCarrier = RequiresNativeCarrier(module, function.returnType) || function.parameters.Any(parameter => RequiresNativeCarrier(module, parameter.type));
        if (!hasCarrier)
        {
            writer.Append("        ").Append(modifiers).Append(' ').Append(function.returnType.managedName).Append(' ').Append(GetRawManagedName(function)).Append("Native(");
            EmitParameters(writer, function.parameters, module.generateMetadata);
            writer.AppendLine(");");
            return;
        }

        string returnType = GetNativeCarrierType(module, function.returnType);
        writer.Append("        ").Append(modifiers).Append(' ').Append(returnType).Append(' ').Append(GetRawManagedName(function)).Append("Interop(");
        EmitNativeParameters(writer, module, function.parameters);
        writer.AppendLine(");");
        EmitCarrierAdapter(writer, module, function);
    }

    private static void EmitCarrierAdapter(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function
    ) {
        writer.Append("        internal static ").Append(function.returnType.managedName).Append(' ').Append(GetRawManagedName(function)).Append("Native(");
        EmitParameters(writer, function.parameters);
        writer.AppendLine(")");
        writer.AppendLine("        {");
        writer.Append("            ");
        if (function.returnType.managedName != "void")
            writer.Append("return ");
        if (IsOpaqueHandle(module, function.returnType))
            writer.Append("new ").Append(function.returnType.managedName).Append('(');
        else if (RequiresNativeCarrier(module, function.returnType))
            writer.Append('(').Append(function.returnType.managedName).Append(')');
        writer.Append(GetRawManagedName(function)).Append("Interop(");
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            BindingParameter parameter = function.parameters[index];
            if (!IsOpaqueHandle(module, parameter.type) && RequiresNativeCarrier(module, parameter.type))
                writer.Append('(').Append(GetNativeCarrierType(module, parameter.type)).Append(')');
            writer.Append(parameter.managedName);
            if (IsOpaqueHandle(module, parameter.type))
                writer.Append(".Handle");
        }

        writer.Append(')');
        if (IsOpaqueHandle(module, function.returnType))
            writer.Append(')');
        writer.AppendLine(";");
        writer.AppendLine("        }");
    }

    private static bool IsOpaqueHandle(
        BindingModule module,
        BindingTypeReference type
    ) => module.types.Any(candidate => candidate.kind == BindingTypeKind.OpaqueHandle && candidate.managedName == type.managedName);
    private static string GetNativeCarrierType(
        BindingModule module,
        BindingTypeReference type
    ) {
        if (IsOpaqueHandle(module, type))
            return "nint";
        if (type.pointerDepth == 0)
        {
            BindingType? enumeration = module.types.FirstOrDefault(candidate =>
                candidate.kind == BindingTypeKind.Enumeration && candidate.managedName == type.managedName);
            if (enumeration?.underlyingType != null)
                return enumeration.underlyingType.managedName;
        }
        return type.managedName;
    }

    private static bool RequiresNativeCarrier(
        BindingModule module,
        BindingTypeReference type
    ) => GetNativeCarrierType(module, type) != type.managedName;
    private static void EmitNativeParameters(
        StringBuilder writer,
        BindingModule module,
        IReadOnlyList<BindingParameter> parameters
    ) {
        for (int index = 0; index < parameters.Count; index++)
        {
            BindingParameter parameter = parameters[index];
            EmitParameter(writer, parameter, index > 0, module.generateMetadata, GetNativeCarrierType(module, parameter.type));
        }
    }

    private static void EmitFunctionTableCall(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function
    ) {
        int tableIndex = function.functionTableIndex.GetValueOrDefault();
        bool hasCarrier = RequiresNativeCarrier(module, function.returnType) || function.parameters.Any(parameter => RequiresNativeCarrier(module, parameter.type));
        writer.Append("        internal static ").Append(GetNativeCarrierType(module, function.returnType)).Append(' ').Append(GetRawManagedName(function)).Append(hasCarrier ? "Interop(" : "Native(");
        EmitNativeParameters(writer, module, function.parameters);
        writer.AppendLine(")");
        writer.AppendLine("        {");
        writer.Append("            ");
        if (!string.Equals(function.returnType.managedName, "void", StringComparison.Ordinal))
            writer.Append("return ");
        writer.Append("((delegate* unmanaged[").Append(GetUnmanagedCallingConvention(function.callingConvention)).Append("]<");
        foreach (BindingParameter parameter in function.parameters)
            writer.Append(GetNativeCarrierType(module, parameter.type)).Append(", ");
        writer.Append(GetNativeCarrierType(module, function.returnType)).Append(">)funcTable[").Append(tableIndex).Append("])(");
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            writer.Append(function.parameters[index].managedName);
        }

        writer.AppendLine(");");
        writer.AppendLine("        }");
        if (hasCarrier)
            EmitCarrierAdapter(writer, module, function);
    }

    private static void EmitFunctionTable(
        StringBuilder writer,
        BindingModule module,
        string runtimeNamespace
    ) {
        if (module.importMode != BindingImportMode.FunctionTable || module.functionTableEntries.Count == 0)
            return;
        int tableSize = module.functionTableEntries.Max(entry => entry.index) + 1;
        writer.Append("    public unsafe partial class ").AppendLine(module.name);
        writer.AppendLine("    {");
        string runtimePrefix = "global::" + runtimeNamespace + ".";
        writer.Append("        internal static ").Append(runtimePrefix).AppendLine("FunctionTable funcTable = null!;");
        writer.AppendLine();
        if (module.useCustomContext)
        {
            writer.Append("        public static void InitApi(").Append(runtimePrefix).AppendLine("INativeContext context)");
            writer.AppendLine("        {");
            writer.Append("            var candidate = new ").Append(runtimePrefix).Append("FunctionTable(context, ").Append(tableSize).AppendLine(");");
            EmitFunctionTableLoads(writer, module);
            writer.AppendLine("        }");
        }
        else
        {
            if (string.Equals(module.getLibraryNameFunctionName, "GetLibraryName", StringComparison.Ordinal))
            {
                writer.Append("        private static string GetLibraryName() => \"").Append(EscapeString(module.libraryName)).AppendLine("\";");
                writer.AppendLine();
            }

            writer.AppendLine("        public static void InitApi()");
            writer.AppendLine("        {");
            writer.Append("            var candidate = new ").Append(runtimePrefix).Append("FunctionTable(").Append(runtimePrefix).Append("LibraryLoader.LoadLibrary(").Append(module.getLibraryNameFunctionName).Append(", ").Append(module.getLibraryExtensionFunctionName ?? "null").Append("), ").Append(tableSize).AppendLine(");");
            EmitFunctionTableLoads(writer, module);
            writer.AppendLine("        }");
        }

        writer.AppendLine();
        writer.AppendLine("        public static void FreeApi() => funcTable?.Free();");
        writer.AppendLine("    }");
    }

    private static void EmitFunctionTableLoads(
        StringBuilder writer,
        BindingModule module
    ) {
        writer.AppendLine("            try");
        writer.AppendLine("            {");
        foreach (BindingFunctionTableEntry entry in module.functionTableEntries.OrderBy(entry => entry.index))
            writer.Append("                candidate.LoadRequired(").Append(entry.index).Append(", \"").Append(EscapeString(entry.entryPoint)).AppendLine("\");");
        writer.AppendLine("            }");
        writer.AppendLine("            catch");
        writer.AppendLine("            {");
        writer.AppendLine("                candidate.Free();");
        writer.AppendLine("                throw;");
        writer.AppendLine("            }");
        writer.AppendLine("            var previous = funcTable;");
        writer.AppendLine("            funcTable = candidate;");
        writer.AppendLine("            previous?.Free();");
    }

    private static string EscapeString(string value) => value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);
    private static void EmitParameters(
        StringBuilder writer,
        IReadOnlyList<BindingParameter> parameters,
        bool metadata = false
    ) {
        for (int i = 0; i < parameters.Count; i++)
            EmitParameter(writer, parameters[i], i > 0, metadata);
    }

    private static void EmitParameter(
        StringBuilder writer,
        BindingParameter parameter,
        bool prefixComma,
        bool metadata = false,
        string? managedType = null
    ) {
        if (prefixComma)
            writer.Append(", ");
        if (metadata)
        {
            writer.Append("[NativeName(NativeNameType.Param, \"").Append(EscapeString(parameter.nativeName)).Append("\")] ").Append("[NativeName(NativeNameType.Type, \"").Append(EscapeString(parameter.type.nativeName)).Append("\")] ");
        }

        writer.Append(managedType ?? parameter.type.managedName).Append(' ').Append(parameter.managedName);
    }

    private static string GetCallingConvention(string value)
    {
        return value switch
        {
            "X86StdCall" => "StdCall",
            "X86ThisCall" => "ThisCall",
            "X86FastCall" => "FastCall",
            _ => "Cdecl"
        };
    }

    private static string GetUnmanagedCallingConvention(string value)
    {
        return value switch
        {
            "X86StdCall" => "Stdcall",
            "X86ThisCall" => "Thiscall",
            "X86FastCall" => "Fastcall",
            _ => "Cdecl"
        };
    }
