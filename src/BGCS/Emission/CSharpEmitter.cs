using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using BGCS.Core.Collections;
using BGCS.Intermediate.Emission;

namespace BGCS.Emission;

using System.Text;
using BGCS.CSharp;
using BGCS.Intermediate;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

/// <summary>
/// Emits the ABI-level C# surface from shared binding IR.
/// </summary>
public sealed class CSharpEmitter : IBindingEmitter
{
    /// <inheritdoc/>
    public string name => "C# ABI emitter";

    /// <inheritdoc/>
    public IReadOnlyList<string> Emit(
        BindingModule module,
        EmissionContext context
    ) {
        ArgumentNullException.ThrowIfNull(module);
        ArgumentNullException.ThrowIfNull(context);
        IReadOnlyList<BindingDiagnostic> diagnostics = Validate(module);
        if (diagnostics.Count > 0)
            throw new BindingEmissionException(diagnostics);
        if (!context.singleFile)
            return EmitSplit(module, context);
        string outputFile = Path.Combine(context.outputPath, context.singleFileName);
        Directory.CreateDirectory(context.outputPath);
        StringBuilder writer = new();
        writer.AppendLine("// <auto-generated/>");
        writer.Append("// ABI reference target: ").AppendLine(module.targetAbi);
        writer.AppendLine("#nullable enable");
        writer.AppendLine("#pragma warning disable CS1591 // Native declarations may omit documentation.");
        writer.AppendLine("using System;");
        writer.AppendLine("using System.Diagnostics;");
        writer.AppendLine("using System.Runtime.CompilerServices;");
        writer.AppendLine("using System.Runtime.InteropServices;");
        writer.Append("using ").Append(context.runtimeNamespace).AppendLine(";");
        foreach (string @using in module.usings.Distinct(StringComparer.Ordinal))
        {
            string normalized = @using.Trim();
            if (normalized.StartsWith("using ", StringComparison.Ordinal))
                normalized = normalized[6..];
            normalized = normalized.TrimEnd(';');
            if (normalized.Length > 0 && !string.Equals(normalized, context.runtimeNamespace, StringComparison.Ordinal))
                writer.Append("using ").Append(normalized).AppendLine(";");
        }

        writer.AppendLine();
        EmitAliases(writer, module);
        writer.Append("namespace ").AppendLine(module.@namespace);
        writer.AppendLine("{");
        HashSet<string> emittedTypes = new(StringComparer.Ordinal);
        foreach (BindingType type in module.types.Where(type => type.kind != BindingTypeKind.Alias))
        {
            if (!emittedTypes.Add(type.managedName))
                continue;
            EmitTypeDocument(writer, type, module);
        }

        EmitDelegatesDocument(writer, module);
        EmitConstants(writer, module);
        EmitPointerHandlesDocument(writer, module);
        EmitFunctions(writer, module);
        EmitFunctionTable(writer, module, context.runtimeNamespace);
        writer.AppendLine("}");
        File.WriteAllText(outputFile, FormatSource(writer.ToString()));
        return [outputFile];
    }

    private static IReadOnlyList<string> EmitSplit(
        BindingModule module,
        EmissionContext context
    ) {
        Directory.CreateDirectory(context.outputPath);
        List<string> outputs = [];
        if (!context.oneFilePerType)
        {
            string path = Path.Combine(context.outputPath, module.name + ".Generated.cs");
            WriteDocument(path, module, context, writer =>
            {
                HashSet<string> emittedTypes = new(StringComparer.Ordinal);
                foreach (BindingType type in module.types.Where(type => type.kind != BindingTypeKind.Alias))
                {
                    if (emittedTypes.Add(type.managedName))
                        EmitTypeDocument(writer, type, module);
                }

                EmitDelegatesDocument(writer, module);
                EmitConstants(writer, module);
                EmitPointerHandlesDocument(writer, module);
                EmitFunctions(writer, module);
                EmitFunctionTable(writer, module, context.runtimeNamespace);
            });
            outputs.Add(path);
            return outputs;
        }

        string typesDirectory = Path.Combine(context.outputPath, "Types");
        Directory.CreateDirectory(typesDirectory);
        HashSet<string> emitted = new(StringComparer.Ordinal);
        foreach (BindingType type in module.types.Where(type => type.kind != BindingTypeKind.Alias))
        {
            if (!emitted.Add(type.managedName))
                continue;
            string path = Path.Combine(typesDirectory, SanitizeFileComponent(type.managedName) + ".g.cs");
            WriteDocument(path, module, context, writer =>
            {
                EmitTypeDocument(writer, type, module);
            });
            outputs.Add(path);
        }

        if (module.delegates.Count > 0)
        {
            string path = Path.Combine(context.outputPath, "Delegates.g.cs");
            WriteDocument(path, module, context, writer =>
            {
                EmitDelegatesDocument(writer, module);
            });
            outputs.Add(path);
        }

        if (module.constants.Count > 0)
        {
            string path = Path.Combine(context.outputPath, "Constants.g.cs");
            WriteDocument(path, module, context, writer => EmitConstants(writer, module));
            outputs.Add(path);
        }

        if (module.functions.Count > 0)
        {
            string path = Path.Combine(context.outputPath, module.name + ".Functions.g.cs");
            WriteDocument(path, module, context, writer =>
            {
                EmitPointerHandlesDocument(writer, module);
                EmitFunctions(writer, module);
                EmitFunctionTable(writer, module, context.runtimeNamespace);
            });
            outputs.Add(path);
        }

        return outputs;
    }

    private static void WriteDocument(
        string path,
        BindingModule module,
        EmissionContext context,
        Action<StringBuilder> emitBody
    ) {
        StringBuilder writer = new();
        writer.AppendLine("// <auto-generated/>");
        writer.Append("// ABI reference target: ").AppendLine(module.targetAbi);
        writer.AppendLine("#nullable enable");
        writer.AppendLine("#pragma warning disable CS1591 // Native declarations may omit documentation.");
        writer.AppendLine("using System;");
        writer.AppendLine("using System.Diagnostics;");
        writer.AppendLine("using System.Runtime.CompilerServices;");
        writer.AppendLine("using System.Runtime.InteropServices;");
        writer.Append("using ").Append(context.runtimeNamespace).AppendLine(";");
        foreach (string @using in module.usings.Distinct(StringComparer.Ordinal))
        {
            string normalized = @using.Trim();
            if (normalized.StartsWith("using ", StringComparison.Ordinal))
                normalized = normalized[6..];
            normalized = normalized.TrimEnd(';');
            if (normalized.Length > 0 && !string.Equals(normalized, context.runtimeNamespace, StringComparison.Ordinal))
                writer.Append("using ").Append(normalized).AppendLine(";");
        }

        writer.AppendLine();
        writer.Append("namespace ").AppendLine(module.@namespace);
        writer.AppendLine("{");
        emitBody(writer);
        writer.AppendLine("}");
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, FormatSource(writer.ToString()));
    }

    private static string FormatSource(string source)
    {
        SyntaxTree tree = CSharpSyntaxTree.ParseText(source);
        Diagnostic[] errors = tree.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length > 0)
            throw new InvalidOperationException("Cannot format invalid generated C# source: " + string.Join(Environment.NewLine, errors.Select(error => error.ToString())));
        return tree.GetCompilationUnitRoot().NormalizeWhitespace("    ", Environment.NewLine).ToFullString() + Environment.NewLine;
    }

    private static string SanitizeFileComponent(string value)
    {
        char[] invalid = Path.GetInvalidFileNameChars();
        return new string(value.Select(character => invalid.Contains(character) ? '_' : character).ToArray());
    }

    /// <summary>
    /// Checks frozen declarations for semantics that this emitter cannot represent safely.
    /// </summary>
    /// <param name="module">
    /// The AST-independent module to validate without writing output.
    /// </param>
    /// <returns>
    /// An immutable diagnostic list, empty when emission can preserve all represented semantics.
    /// </returns>
    public IReadOnlyList<BindingDiagnostic> Validate(BindingModule module)
    {
        ArgumentNullException.ThrowIfNull(module);
        List<BindingDiagnostic> diagnostics = [];
        HashSet<string> opaqueStorageTypes = EnumerateTypes(module.types).Where(type => type.isOpaqueStorage).Select(type => type.managedName).ToHashSet(StringComparer.Ordinal);
        Dictionary<string, string> aliases = module.types.Where(type => type.kind == BindingTypeKind.Alias && type.underlyingType != null).GroupBy(type => type.managedName, StringComparer.Ordinal).ToDictionary(group => group.Key, group => group.First().underlyingType!.managedName, StringComparer.Ordinal);
        foreach (BindingType type in module.types)
        {
            if (type.kind is BindingTypeKind.FunctionPointer or BindingTypeKind.Unexposed)
            {
                AddUnsupported(diagnostics, $"Type '{type.nativeName}' has kind '{type.kind}', which the IR-native C# emitter cannot preserve yet.");
            }

            if (type.kind == BindingTypeKind.Alias && type.underlyingType == null)
            {
                AddUnsupported(diagnostics, $"Alias '{type.nativeName}' does not identify its underlying type.");
            }

            foreach (BindingField field in type.fields.Where(field => field.isBitField && field.bitWidth > 0))
            {
                int storageBits = field.type.size * 8;
                if (field.type.size is not (1 or 2 or 4 or 8) || field.bitWidth > storageBits)
                {
                    AddUnsupported(diagnostics, $"Field '{type.nativeName}.{field.nativeName}' is a {field.bitWidth}-bit bitfield with unsupported {field.type.size}-byte storage.");
                }
            }
        }

        foreach (BindingFunction function in module.functions)
        {
            if (function.kind != BindingFunctionKind.Free)
            {
                AddUnsupported(diagnostics, $"Callable '{function.nativeName}' has kind '{function.kind}'; only free C ABI functions are supported by this emitter.");
            }

            if (function.isVariadic)
            {
                AddUnsupported(diagnostics, $"Function '{function.nativeName}' is variadic and requires explicitly configured fixed signatures.");
            }

            ValidateOpaqueByValue(diagnostics, opaqueStorageTypes, aliases, function.returnType, $"return type of function '{function.nativeName}'");
            foreach (BindingParameter parameter in function.parameters)
            {
                ValidateOpaqueByValue(diagnostics, opaqueStorageTypes, aliases, parameter.type, $"parameter '{parameter.nativeName}' of function '{function.nativeName}'");
            }

            if (function.returnMarshalling.requiresCleanup)
            {
                BindingFunction? cleanup = string.IsNullOrWhiteSpace(function.returnMarshalling.cleanupFunction) ? null : module.functions.FirstOrDefault(candidate => string.Equals(candidate.nativeName, function.returnMarshalling.cleanupFunction, StringComparison.Ordinal));
                if (cleanup == null || cleanup.parameters.Count != 1)
                {
                    AddUnsupported(diagnostics, $"Function '{function.nativeName}' requires return cleanup, but cleanup function '{function.returnMarshalling.cleanupFunction ?? "<missing>"}' is not a one-parameter callable in the module.");
                }
            }

            if (module.importMode == BindingImportMode.FunctionTable && function.functionTableIndex == null)
            {
                AddUnsupported(diagnostics, $"Function-table callable '{function.nativeName}' does not have an assigned slot.");
            }

            if (module.importMode == BindingImportMode.FunctionTable && function.functionTableIndex is int index && !module.functionTableEntries.Any(entry => entry.index == index && string.Equals(entry.entryPoint, function.nativeName, StringComparison.Ordinal)))
            {
                AddUnsupported(diagnostics, $"Function-table callable '{function.nativeName}' has slot {index}, but the module does not define the matching entry point.");
            }
        }

        foreach (BindingDelegate bindingDelegate in module.delegates)
        {
            ValidateOpaqueByValue(diagnostics, opaqueStorageTypes, aliases, bindingDelegate.returnType, $"return type of delegate '{bindingDelegate.nativeName}'");
            foreach (BindingParameter parameter in bindingDelegate.parameters)
            {
                ValidateOpaqueByValue(diagnostics, opaqueStorageTypes, aliases, parameter.type, $"parameter '{parameter.nativeName}' of delegate '{bindingDelegate.nativeName}'");
            }
        }

        if (module.importMode == BindingImportMode.FunctionTable)
        {
            foreach (IGrouping<int, BindingFunctionTableEntry> duplicate in module.functionTableEntries.GroupBy(entry => entry.index).Where(group => group.Count() > 1))
            {
                AddUnsupported(diagnostics, $"Function-table slot {duplicate.Key} is assigned more than once.");
            }
        }

        return diagnostics.AsReadOnly();
    }

    private static IEnumerable<BindingType> EnumerateTypes(IEnumerable<BindingType> types)
    {
        foreach (BindingType type in types)
        {
            yield return type;
            foreach (BindingType nested in EnumerateTypes(type.nestedTypes))
                yield return nested;
        }
    }

    private static void ValidateOpaqueByValue(
        ICollection<BindingDiagnostic> diagnostics,
        ISet<string> opaqueStorageTypes,
        IReadOnlyDictionary<string, string> aliases,
        BindingTypeReference reference,
        string location
    ) {
        if (reference.pointerDepth > 0 || reference.managedName.Contains('*'))
            return;
        string managedName = reference.managedName;
        HashSet<string> visited = new(StringComparer.Ordinal);
        while (visited.Add(managedName) && aliases.TryGetValue(managedName, out string? target))
            managedName = target;
        if (opaqueStorageTypes.Contains(managedName))
        {
            AddUnsupported(diagnostics, $"The {location} uses opaque storage type '{managedName}' by value; expose its native definition or use a pointer so ABI classification is unambiguous.");
        }
    }

    private static void EmitAliases(
        StringBuilder writer,
        BindingModule module
    ) {
        HashSet<string> concreteTypes = module.types.Where(type => type.kind != BindingTypeKind.Alias).Select(type => type.managedName).ToHashSet(StringComparer.Ordinal);
        foreach (BindingType type in module.types.Where(type => type.kind == BindingTypeKind.Alias && type.underlyingType != null))
        {
            if (CsType.IsKnownPrimitive(type.managedName))
                continue;
            string target = type.underlyingType!.managedName.Contains('*') ? "nint" : type.underlyingType.managedName;
            if (concreteTypes.Contains(type.managedName))
                continue;
            if (!CsType.IsKnownPrimitive(target) && concreteTypes.Contains(target))
                target = $"global::{module.@namespace}.{target}";
            if (!string.Equals(type.managedName, target, StringComparison.Ordinal))
                writer.Append("using ").Append(type.managedName).Append(" = ").Append(target).AppendLine(";");
        }

        if (module.types.Any(type => type.kind == BindingTypeKind.Alias && type.underlyingType != null))
            writer.AppendLine();
    }

    private static void EmitTypeDocument(
        StringBuilder writer,
        BindingType type,
        BindingModule module
    ) {
        if (!module.nestGeneratedTypesInApi)
        {
            EmitType(writer, type, module);
            return;
        }

        EmitNestedInApi(writer, module, nested => EmitType(nested, type, module));
    }

    private static void EmitDelegatesDocument(
        StringBuilder writer,
        BindingModule module
    ) {
        if (module.delegates.Count == 0)
            return;
        if (!module.nestGeneratedTypesInApi)
        {
            EmitDelegates(writer, module);
            return;
        }

        EmitNestedInApi(writer, module, nested => EmitDelegates(nested, module));
    }

    private static void EmitPointerHandlesDocument(
        StringBuilder writer,
        BindingModule module
    ) {
        if (!module.wrapPointersAsHandle || GetPointerHandleSpecs(module).Count == 0)
            return;
        if (!module.nestGeneratedTypesInApi)
        {
            EmitPointerHandles(writer, module);
            return;
        }

        EmitNestedInApi(writer, module, nested => EmitPointerHandles(nested, module));
    }

    private static void EmitNestedInApi(
        StringBuilder writer,
        BindingModule module,
        Action<StringBuilder> emit
    ) {
        writer.Append("    public unsafe partial class ").AppendLine(module.name);
        writer.AppendLine("    {");
        StringBuilder nested = new();
        emit(nested);
        AppendIndented(writer, nested, "    ");
        writer.AppendLine("    }");
        writer.AppendLine();
    }

    private static void EmitDelegates(
        StringBuilder writer,
        BindingModule module
    ) {
        foreach (BindingDelegate bindingDelegate in module.delegates)
        {
            EmitPlaceholderComment(writer, module, 1);
            writer.Append("    [UnmanagedFunctionPointer(CallingConvention.").Append(GetCallingConvention(bindingDelegate.callingConvention)).AppendLine(")] ");
            writer.Append("    public unsafe delegate ").Append(bindingDelegate.returnType.managedName).Append(' ').Append(bindingDelegate.managedName).Append('(');
            EmitParameters(writer, bindingDelegate.parameters);
            writer.AppendLine(");");
            writer.AppendLine();
        }
    }

    private static void EmitConstants(
        StringBuilder writer,
        BindingModule module
    ) {
        if (module.constants.Count == 0)
            return;
        writer.Append("    public unsafe partial class ").AppendLine(module.name);
        writer.AppendLine("    {");
        foreach (BindingConstant constant in module.constants)
            writer.Append("        public const ").Append(constant.managedType).Append(' ').Append(constant.managedName).Append(" = ").Append(constant.value).AppendLine(";");
        writer.AppendLine("    }");
        writer.AppendLine();
    }

    private static void AddUnsupported(
        ICollection<BindingDiagnostic> diagnostics,
        string message
    ) {
        diagnostics.Add(new BindingDiagnostic(BindingDiagnosticSeverity.Error, message, BindingDiagnosticCodes.C_CSHARPUNSUPPORTED));
    }

    private static void EmitType(
        StringBuilder writer,
        BindingType type,
        BindingModule? module = null
    ) {
        EmitComment(writer, type.comment, 1);
        if (module != null)
            EmitPlaceholderComment(writer, module, 1, type.comment);
        foreach (string attribute in type.attributes)
            writer.Append("    ").AppendLine(attribute);
        switch (type.kind)
        {
            case BindingTypeKind.Enumeration:
                string underlying = type.underlyingType?.managedName ?? (type.size > 4 ? "long" : "int");
                writer.Append("    public enum ").Append(type.managedName).Append(" : ").AppendLine(underlying);
                writer.AppendLine("    {");
                foreach (BindingEnumMember item in type.enumMembers)
                {
                    EmitComment(writer, item.comment, 2);
                    foreach (string attribute in item.attributes)
                        writer.Append("        ").AppendLine(attribute);
                    string value = type.isCustomDefinition ? item.value : $"unchecked({item.value})";
                    writer.Append("        ").Append(item.managedName).Append(" = ").Append(value).AppendLine(",");
                }

                writer.AppendLine("    }");
                writer.AppendLine();
                break;
            case BindingTypeKind.Structure:
            case BindingTypeKind.Union:
                bool explicitLayout = type.kind == BindingTypeKind.Union || type.fields.Any(field => field.isBitField);
                bool opaqueStorage = type.nestedTypes.Count == 0 && type.fields.Count == 0;
                writer.Append("    [StructLayout(LayoutKind.").Append(explicitLayout ? "Explicit" : "Sequential");
                if (type.size > 0)
                    writer.Append(", Size = ").Append(type.size);
                if (type.size > 0 && type.alignment is 1 or 2 or 4 or 8 or 16)
                    writer.Append(", Pack = ").Append(type.alignment);
                writer.AppendLine(")] ");
                writer.Append("    public partial struct ").AppendLine(type.managedName);
                writer.AppendLine("    {");
                foreach (BindingType nestedType in type.nestedTypes)
                {
                    StringBuilder nestedWriter = new();
                    EmitType(nestedWriter, nestedType, module);
                    AppendIndented(writer, nestedWriter, "    ");
                }

                if (type.nestedTypes.Count == 0 && type.fields.Count == 0)
                {
                    writer.AppendLine("#pragma warning disable CS0169");
                    if (explicitLayout)
                        writer.AppendLine("        [FieldOffset(0)]");
                    writer.Append("        private ").Append(GetAlignmentStorageType(type.alignment)).AppendLine(" _opaque;");
                    writer.AppendLine("#pragma warning restore CS0169");
                }

                int bitfieldIndex = 0;
                for (int fieldIndex = 0; fieldIndex < type.fields.Count; fieldIndex++)
                {
                    BindingField field = type.fields[fieldIndex];
                    if (!field.isBitField)
                    {
                        EmitField(writer, field, explicitLayout);
                        continue;
                    }

                    if (field.bitWidth <= 0)
                        continue;
                    fieldIndex = EmitBitfieldGroup(writer, type.fields, fieldIndex, bitfieldIndex++);
                }

                if (type.validity != null)
                {
                    writer.Append("        public readonly bool ").Append(type.validity.propertyName).Append(" => ").Append(type.validity.fieldName).Append(" != ").Append(type.validity.invalidValue).AppendLine(";");
                }

                if (module?.generateSizeOfStructs == true)
                    writer.Append("        public static readonly int SizeInBytes = ").Append(type.size).AppendLine(";");
                if (module?.generateConstructorsForStructs == true && type.kind == BindingTypeKind.Structure && type.fields.Count > 0)
                    EmitStructConstructor(writer, type);
                writer.AppendLine("    }");
                writer.AppendLine();
                break;
            case BindingTypeKind.OpaqueHandle:
                writer.AppendLine("    [DebuggerDisplay(\"{DebuggerDisplay,nq}\")] ");
                writer.Append("    public readonly partial struct ").Append(type.managedName).AppendLine(" : IEquatable<" + type.managedName + ">");
                writer.AppendLine("    {");
                writer.Append("        public ").Append(type.managedName).AppendLine("(nint handle) { Handle = handle; }");
                writer.AppendLine("        public nint Handle { get; }");
                writer.AppendLine("        public bool IsNull => Handle == 0;");
                writer.Append("        public static ").Append(type.managedName).Append(" Null => new ").Append(type.managedName).AppendLine("(0);");
                writer.Append("        public static implicit operator ").Append(type.managedName).Append("(nint handle) => new ").Append(type.managedName).AppendLine("(handle);");
                writer.Append("        public static bool operator ==(").Append(type.managedName).Append(" left, ").Append(type.managedName).AppendLine(" right) => left.Handle == right.Handle;");
                writer.Append("        public static bool operator !=(").Append(type.managedName).Append(" left, ").Append(type.managedName).AppendLine(" right) => left.Handle != right.Handle;");
                writer.Append("        public bool Equals(").Append(type.managedName).AppendLine(" other) => Handle == other.Handle;");
                writer.AppendLine("        public override bool Equals(object? obj) => obj is " + type.managedName + " other && Equals(other);");
                writer.AppendLine("        public override int GetHashCode() => Handle.GetHashCode();");
                writer.Append("        private string DebuggerDisplay => string.Format(\"").Append(type.managedName).AppendLine(" [0x{0}]\", Handle.ToString(\"X\"));");
                writer.AppendLine("    }");
                writer.AppendLine();
                break;
        }
    }

    private static void AppendIndented(
        StringBuilder writer,
        StringBuilder content,
        string indent
    ) {
        using StringReader reader = new(content.ToString());
        while (reader.ReadLine() is { } line)
        {
            if (line.Length > 0)
                writer.Append(indent);
            writer.AppendLine(line);
        }
    }

    private static void EmitComment(
        StringBuilder writer,
        string? comment,
        int indent
    ) {
        if (string.IsNullOrWhiteSpace(comment))
            return;
        string padding = new(' ', indent * 4);
        if (comment.TrimStart().StartsWith("//", StringComparison.Ordinal))
        {
            foreach (string line in comment.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n'))
                writer.Append(padding).AppendLine(line);
            return;
        }

        writer.Append(padding).AppendLine("/// <summary>");
        writer.Append(padding).Append("/// ").AppendLine(comment);
        writer.Append(padding).AppendLine("/// </summary>");
    }

    private static void EmitPlaceholderComment(
        StringBuilder writer,
        BindingModule module,
        int indent,
        string? existingComment = null
    ) {
        if (module.generatePlaceholderComments && string.IsNullOrWhiteSpace(existingComment))
            EmitComment(writer, "To be documented.", indent);
    }

    private static void EmitStructConstructor(
        StringBuilder writer,
        BindingType type
    ) {
        BindingField[] fields = type.fields.Where(field => field.arrayDimensions.All(dimension => dimension > 0)).ToArray();
        if (fields.Length == 0)
            return;
        writer.Append("        public unsafe ").Append(type.managedName).Append('(');
        for (int index = 0; index < fields.Length; index++)
        {
            if (index > 0)
                writer.Append(", ");
            BindingField field = fields[index];
            bool array = field.arrayDimensions.Count > 0;
            writer.Append(field.type.managedName);
            if (array)
                writer.Append('*');
            writer.Append(' ').Append(GetConstructorParameterName(field, index)).Append(" = default");
        }

        writer.AppendLine(")");
        writer.AppendLine("        {");
        for (int index = 0; index < fields.Length; index++)
        {
            BindingField field = fields[index];
            string parameterName = GetConstructorParameterName(field, index);
            int count = field.arrayDimensions.Count == 0 ? 1 : field.arrayDimensions.Aggregate(1, (
                value,
                dimension
            ) => dimension <= 0 ? 0 : checked(value * dimension));
            if (field.arrayDimensions.Count == 0)
            {
                writer.Append("            this.").Append(field.managedName).Append(" = ").Append(parameterName).AppendLine(";");
                continue;
            }

            writer.Append("            if (").Append(parameterName).AppendLine(" != null)");
            writer.AppendLine("            {");
            for (int element = 0; element < count; element++)
            {
                writer.Append("                this.").Append(field.managedName);
                if (count > 1)
                    writer.Append('_').Append(element);
                writer.Append(" = ");
                string storageType = GetArrayStorageType(field);
                if (string.Equals(storageType, "nint", StringComparison.Ordinal) && field.type.managedName.Contains('*', StringComparison.Ordinal))
                    writer.Append("(nint)");
                writer.Append(parameterName).Append('[').Append(element).AppendLine("];");
            }

            writer.AppendLine("            }");
        }

        writer.AppendLine("        }");
    }

    private static string GetConstructorParameterName(
        BindingField field,
        int index
    ) {
        string name = string.IsNullOrWhiteSpace(field.nativeName) ? $"value{index}" : field.nativeName.Trim('_');
        if (name.Length == 0)
            return $"value{index}";
        string parameterName = char.ToLowerInvariant(name[0]) + name[1..];
        return SyntaxFacts.GetKeywordKind(parameterName) == SyntaxKind.None ? parameterName : "@" + parameterName;
    }

    private static string GetAlignmentStorageType(int alignment)
    {
        return alignment switch
        {
            2 => "ushort",
            4 => "uint",
            8 => "ulong",
            _ => "byte"
        };
    }

    private static int EmitBitfieldGroup(
        StringBuilder writer,
        IReadOnlyList<BindingField> fields,
        int startIndex,
        int storageIndex
    ) {
        BindingField first = fields[startIndex];
        string storageName = $"RawBits{storageIndex}";
        long storageOffset = first.bitOffset / 8;
        long storageEnd = (first.bitOffset + first.bitWidth + 7) / 8;
        int lastIndex = startIndex;
        for (int index = startIndex; index < fields.Count; index++)
        {
            BindingField field = fields[index];
            if (!field.isBitField || field.bitWidth <= 0 || field.bitOffset < storageOffset * 8)
                break;
            storageEnd = Math.Max(storageEnd, (field.bitOffset + field.bitWidth + 7) / 8);
            lastIndex = index;
        }

        long byteCount = storageEnd - storageOffset;
        for (int byteIndex = 0; byteIndex < byteCount; byteIndex++)
        {
            writer.Append("        [FieldOffset(").Append(storageOffset + byteIndex).AppendLine(")] ");
            writer.Append("        public byte ").Append(storageName).Append('_').Append(byteIndex).AppendLine(";");
        }

        for (int index = startIndex; index <= lastIndex; index++)
        {
            BindingField field = fields[index];
            long relativeBitOffset = field.bitOffset - storageOffset * 8;
            writer.Append("        public ").Append(field.type.managedName).Append(' ').Append(field.managedName);
            writer.Append(" { get => unchecked((").Append(field.type.managedName).Append(")Bitfield.");
            writer.Append(field.isSignedBitField ? "GetSigned" : "Get");
            writer.Append("(MemoryMarshal.CreateReadOnlySpan(ref ").Append(storageName).Append("_0, ").Append(byteCount);
            writer.Append("), ").Append(relativeBitOffset).Append(", ").Append(field.bitWidth).Append(")); ");
            writer.Append("set => Bitfield.Set(MemoryMarshal.CreateSpan(ref ").Append(storageName).Append("_0, ").Append(byteCount);
            writer.Append("), unchecked((ulong)value), ").Append(relativeBitOffset).Append(", ").Append(field.bitWidth).AppendLine("); }");
        }

        return lastIndex;
    }

    private static void EmitField(
        StringBuilder writer,
        BindingField field,
        bool explicitLayout
    ) {
        int count = field.arrayDimensions.Count == 0 ? 1 : field.arrayDimensions.Aggregate(1, (
            value,
            dimension
        ) => dimension <= 0 ? 0 : checked(value * dimension));
        if (count == 0)
        {
            writer.Append("        public const int ").Append(field.managedName).Append("Offset = ").Append(field.offset).AppendLine(";");
            return;
        }

        for (int i = 0; i < count; i++)
        {
            if (explicitLayout)
                writer.Append("        [FieldOffset(").Append(field.offset + i * field.type.size).AppendLine(")] ");
            string storageType = GetArrayStorageType(field);
            writer.Append("        public ");
            if (storageType.Contains('*', StringComparison.Ordinal))
                writer.Append("unsafe ");
            writer.Append(storageType).Append(' ').Append(field.managedName);
            if (count > 1)
                writer.Append('_').Append(i);
            writer.AppendLine(";");
        }

        if (count > 1)
        {
            writer.Append("        public ");
            if (field.type.managedName.Contains('*', StringComparison.Ordinal))
                writer.Append("unsafe ");
            writer.Append("Span<").Append(GetSpanElementType(field.type.managedName)).Append("> ").Append(field.managedName);
            writer.Append(" => MemoryMarshal.CreateSpan(ref ").Append(field.managedName).Append("_0, ").Append(count).AppendLine(");");
        }
    }

    private static string GetArrayStorageType(BindingField field) => field.arrayDimensions.Count > 0 && field.type.managedName.Contains('*', StringComparison.Ordinal) ? GetSpanElementType(field.type.managedName) : field.type.managedName;
    private static void EmitFunctions(
        StringBuilder writer,
        BindingModule module
    ) {
        if (module.functions.Count == 0)
            return;
        writer.Append("    public unsafe partial class ").AppendLine(module.name);
        writer.AppendLine("    {");
        if (module.emitLibraryNameConstant && module.importMode is BindingImportMode.DllImport or BindingImportMode.LibraryImport)
        {
            writer.Append("        internal const string LibName = \"").Append(EscapeString(module.libraryName)).AppendLine("\";");
            writer.AppendLine();
        }

        foreach (BindingFunction function in module.functions.Where(function => function.kind == BindingFunctionKind.Free))
        {
            EmitPlaceholderComment(writer, module, 2);
            if (module.generateMetadata)
            {
                writer.Append("        [NativeName(NativeNameType.Func, \"").Append(EscapeString(function.nativeName)).AppendLine("\")]");
                writer.Append("        [return: NativeName(NativeNameType.Type, \"").Append(EscapeString(function.returnType.nativeName)).AppendLine("\")]");
            }

            switch (module.importMode)
            {
                case BindingImportMode.DllImport:
                    writer.Append("        [DllImport(LibName").Append(", CallingConvention = CallingConvention.").Append(GetCallingConvention(function.callingConvention)).Append(", EntryPoint = \"").Append(function.nativeName).AppendLine("\")]");
                    EmitExternFunction(writer, module, function, "internal static extern");
                    break;
                case BindingImportMode.LibraryImport:
                    writer.Append("        [LibraryImport(LibName").Append(", EntryPoint = \"").Append(function.nativeName).AppendLine("\")] ");
                    if (GetUnmanagedCallingConvention(function.callingConvention) != GetUnmanagedCallingConvention(module.platformDefaultCallingConvention) || module.platformDefaultCallingConvention == "Unknown")
                    {
                        writer.Append("        [UnmanagedCallConv(CallConvs = new Type[] { typeof(CallConv").Append(GetUnmanagedCallingConvention(function.callingConvention)).AppendLine(") })] ");
                    }

                    EmitExternFunction(writer, module, function, "internal static partial");
                    break;
                case BindingImportMode.FunctionTable:
                    EmitFunctionTableCall(writer, module, function);
                    break;
                default:
                    throw new ArgumentOutOfRangeException(nameof(module.importMode), module.importMode, null);
            }

            writer.AppendLine();
        }

        writer.AppendLine("    }");
        writer.AppendLine();
        foreach (IGrouping<string, BindingFunction> group in module.functions.Where(function => function.kind == BindingFunctionKind.Free).GroupBy(function => function.managedKind == BindingManagedFunctionKind.Instance || string.IsNullOrWhiteSpace(function.managedContainer) ? module.name : function.managedContainer!, StringComparer.Ordinal))
        {
            writer.Append("    public ");
            if (string.Equals(group.Key, "Extensions", StringComparison.Ordinal))
                writer.Append("static ");
            writer.Append("unsafe partial class ").AppendLine(group.Key);
            writer.AppendLine("    {");
            string nativeOwner = string.Equals(group.Key, module.name, StringComparison.Ordinal) ? string.Empty : module.name + ".";
            BindingFunction[] functions = group.ToArray();
            HashSet<string> publicSignatures = BuildReservedFunctionSignatures(module, functions);
            foreach (BindingFunction function in functions)
            {
                EmitManagedFunctions(writer, module, function, nativeOwner, publicSignatures);
                writer.AppendLine();
            }

            writer.AppendLine("    }");
            writer.AppendLine();
        }

        foreach (IGrouping<string, BindingFunction> group in module.functions.Where(function => function.kind == BindingFunctionKind.Free && function.managedKind == BindingManagedFunctionKind.Instance && !function.suppressFriendlySurface && !string.IsNullOrWhiteSpace(function.managedReceiverType)).GroupBy(function => function.managedReceiverType!, StringComparer.Ordinal))
        {
            writer.Append("    public unsafe partial struct ").AppendLine(group.Key);
            writer.AppendLine("    {");
            foreach (BindingFunction function in group)
            {
                EmitInstanceManagedFunction(writer, module, function);
                writer.AppendLine();
            }

            writer.AppendLine("    }");
            writer.AppendLine();
        }
    }

    private static void EmitManagedFunctions(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        string nativeOwner,
        HashSet<string> publicSignatures
    ) {
        if (function.suppressFriendlySurface)
        {
            EmitRawManagedFunction(writer, function, nativeOwner);
            return;
        }

        FriendlyFunctionPlan friendly = CreateFriendlyPlan(function);
        if (module.wrapPointersAsHandle && HasPointerHandleUsage(module, function))
        {
            IReadOnlyList<PointerHandleSpec> specs = GetPointerHandleSpecs(module);
            FriendlyFunctionPlan pointerFriendly = CreatePointerHandleFriendlyPlan(friendly, specs, function);
            bool suppressRawHandle = (pointerFriendly.returnsString || pointerFriendly.returnsBool) && !pointerFriendly.hasNonPointerHandleParameterTransform;
            EmitPointerHandleManagedFunctions(writer, module, function, nativeOwner, specs, suppressRawHandle);
            if (friendly.hasTransform)
            {
                if (pointerFriendly.hasNonPointerHandleTransform)
                {
                    writer.AppendLine();
                    EmitFriendlyManagedFunction(writer, module, function, pointerFriendly, nativeOwner);
                }
            }

            EmitDefaultValueOverload(writer, module, function, publicSignatures);
            return;
        }

        bool sameSignatureWithDifferentReturn = (friendly.returnsString || friendly.returnsBool) && !friendly.hasParameterTransform;
        if (!sameSignatureWithDifferentReturn)
            EmitRawManagedFunction(writer, function, nativeOwner);
        if (friendly.hasTransform)
            EmitFriendlyManagedFunction(writer, module, function, friendly, nativeOwner);
        EmitDefaultValueOverload(writer, module, function, publicSignatures);
        EmitCallbackManagedFunction(writer, module, function, nativeOwner);
        EmitAdditionalPointerOverloads(writer, module, function, nativeOwner);
    }

    private static void EmitRawManagedFunction(
        StringBuilder writer,
        BindingFunction function,
        string nativeOwner
    ) {
        writer.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
        writer.Append("        public static ").Append(function.returnType.managedName).Append(' ').Append(function.managedName).Append('(');
        EmitManagedParameters(writer, function, includeReceiverModifier: true);
        writer.AppendLine(")");
        writer.AppendLine("        {");
        writer.Append("            ");
        if (!string.Equals(function.returnType.managedName, "void", StringComparison.Ordinal))
            writer.Append(function.returnType.managedName).Append(" ret = ");
        writer.Append(nativeOwner).Append(GetRawManagedName(function)).Append("Native(");
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            writer.Append(function.parameters[index].managedName);
        }

        writer.AppendLine(");");
        if (!string.Equals(function.returnType.managedName, "void", StringComparison.Ordinal))
            writer.AppendLine("            return ret;");
        writer.AppendLine("        }");
    }

    private static void EmitManagedParameters(
        StringBuilder writer,
        BindingFunction function,
        bool includeReceiverModifier
    ) {
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            BindingParameter parameter = function.parameters[index];
            if (includeReceiverModifier && function.managedKind == BindingManagedFunctionKind.Extension && function.managedReceiverIndex == index)
                writer.Append("this ");
            writer.Append(parameter.type.managedName).Append(' ').Append(parameter.managedName);
        }
    }

    private static void EmitDefaultValueOverload(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        HashSet<string> publicSignatures
    ) {
        if (function.managedKind == BindingManagedFunctionKind.Extension)
            return;
        FriendlyFunctionPlan friendly = CreateFriendlyPlan(function);
        if (module.wrapPointersAsHandle && HasPointerHandleUsage(module, function))
            friendly = CreatePointerHandleFriendlyPlan(friendly, GetPointerHandleSpecs(module), function);
        foreach (IReadOnlySet<int> omitted in EnumerateDefaultOmissionSets(function, friendly))
        {
            string signature = BuildFriendlySignatureKey(function, friendly, omitted);
            if (!publicSignatures.Add(signature))
                continue;
            EmitFriendlyDefaultValueOverload(writer, module, function, friendly, omitted);
        }
    }

    private static IReadOnlyList<IReadOnlySet<int>> EnumerateDefaultOmissionSets(
        BindingFunction function,
        FriendlyFunctionPlan plan
    ) {
        int[] defaultable = plan.parameters.Where(parameter => parameter.parameter.defaultValue != null && parameter.kind is not (FriendlyParameterKind.Span or FriendlyParameterKind.Ref or FriendlyParameterKind.Out or FriendlyParameterKind.RefBool)).Select(parameter => function.parameters.IndexOf(parameter.parameter)).Where(index => index >= 0).Distinct().Order().ToArray();
        if (defaultable.Length == 0)
            return [];
        List<(HashSet<int> Omitted, bool Suffix, string Order)> sets = [];
        Enumerate(0, []);
        return sets.OrderByDescending(item => item.Suffix).ThenByDescending(item => item.Omitted.Count).ThenBy(item => item.Order, StringComparer.Ordinal).Select(item => (IReadOnlySet<int>)item.Omitted).ToArray();
        void Enumerate(
            int position,
            HashSet<int> omitted
        ) {
            if (position < defaultable.Length)
            {
                Enumerate(position + 1, omitted);
                HashSet<int> withCurrent = new(omitted)
                {
                    defaultable[position]
                };
                Enumerate(position + 1, withCurrent);
                return;
            }

            if (omitted.Count == 0)
                return;
            bool suffix = true;
            bool sawOmitted = false;
            StringBuilder order = new(defaultable.Length);
            foreach (int index in defaultable)
            {
                bool isOmitted = omitted.Contains(index);
                order.Append(isOmitted ? '1' : '0');
                sawOmitted |= isOmitted;
                if (sawOmitted && !isOmitted)
                    suffix = false;
            }

            sets.Add((omitted, suffix, order.ToString()));
        }
    }

    private static string BuildFriendlySignatureKey(
        BindingFunction function,
        FriendlyFunctionPlan plan,
        IReadOnlySet<int>? omitted
    ) {
        StringBuilder key = new(function.managedName);
        foreach (FriendlyParameterPlan parameter in plan.parameters)
        {
            int nativeIndex = function.parameters.IndexOf(parameter.parameter);
            if (omitted?.Contains(nativeIndex) == true)
                continue;
            key.Append('|').Append(parameter.kind switch
            {
                FriendlyParameterKind.Out => "out ",
                FriendlyParameterKind.Ref or FriendlyParameterKind.RefBool => "ref ",
                _ => string.Empty
            }).Append(NormalizeSignatureType(parameter.managedType));
        }

        return key.ToString();
    }

    private static HashSet<string> BuildReservedFunctionSignatures(
        BindingModule module,
        IReadOnlyList<BindingFunction> functions
    ) {
        HashSet<string> signatures = new(StringComparer.Ordinal);
        IReadOnlyList<PointerHandleSpec> specs = module.wrapPointersAsHandle ? GetPointerHandleSpecs(module) : [];
        foreach (BindingFunction function in functions)
        {
            StringBuilder raw = new(function.managedName);
            foreach (BindingParameter parameter in function.parameters)
                raw.Append('|').Append(NormalizeSignatureType(parameter.type.managedName));
            signatures.Add(raw.ToString());
            if (function.suppressFriendlySurface)
                continue;
            FriendlyFunctionPlan friendly = CreateFriendlyPlan(function);
            if (module.wrapPointersAsHandle && HasPointerHandleUsage(module, function))
                friendly = CreatePointerHandleFriendlyPlan(friendly, specs, function);
            signatures.Add(BuildFriendlySignatureKey(function, friendly, null));
        }

        return signatures;
    }

    private static void EmitFriendlyDefaultValueOverload(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        FriendlyFunctionPlan plan,
        IReadOnlySet<int> omitted
    ) {
        writer.AppendLine();
        EmitPlaceholderComment(writer, module, 2);
        string returnType = GetFriendlyReturnType(function, plan);
        writer.Append("        public static ").Append(returnType).Append(' ').Append(function.managedName).Append('(');
        bool firstParameter = true;
        foreach (FriendlyParameterPlan parameter in plan.parameters)
        {
            if (omitted.Contains(function.parameters.IndexOf(parameter.parameter)))
                continue;
            if (!firstParameter)
                writer.Append(", ");
            firstParameter = false;
            if (parameter.kind == FriendlyParameterKind.Out)
                writer.Append("out ");
            else if (parameter.kind is FriendlyParameterKind.Ref or FriendlyParameterKind.RefBool)
                writer.Append("ref ");
            writer.Append(parameter.managedType).Append(' ').Append(parameter.parameter.managedName);
        }

        writer.AppendLine(")");
        writer.AppendLine("        {");
        writer.Append("            ");
        if (!string.Equals(returnType, "void", StringComparison.Ordinal))
            writer.Append("return ");
        writer.Append(function.managedName).Append('(');
        for (int index = 0; index < plan.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            FriendlyParameterPlan parameter = plan.parameters[index];
            int nativeIndex = function.parameters.IndexOf(parameter.parameter);
            if (!omitted.Contains(nativeIndex))
            {
                if (parameter.kind == FriendlyParameterKind.Out)
                    writer.Append("out ");
                else if (parameter.kind is FriendlyParameterKind.Ref or FriendlyParameterKind.RefBool)
                    writer.Append("ref ");
                writer.Append(parameter.parameter.managedName);
            }
            else
            {
                writer.Append(FormatFriendlyDefault(parameter));
            }
        }

        writer.AppendLine(");");
        writer.AppendLine("        }");
    }

    private static string FormatFriendlyDefault(FriendlyParameterPlan parameter)
    {
        string value = parameter.parameter.defaultValue?.Trim() ?? "default";
        if (parameter.kind == FriendlyParameterKind.String)
            return value is "NULL" or "nullptr" ? "(string?)null" : value == "default" ? "(string?)default" : value;
        if (value is "NULL" or "nullptr")
            return "default";
        return parameter.kind switch
        {
            FriendlyParameterKind.Bool when string.Equals(value, "true", StringComparison.OrdinalIgnoreCase) => "true",
            FriendlyParameterKind.Bool when string.Equals(value, "false", StringComparison.OrdinalIgnoreCase) => "false",
            FriendlyParameterKind.Bool => $"({value}) != 0",
            _ => $"({parameter.managedType})({value})"
        };
    }

    private static void EmitInstanceManagedFunction(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function
    ) {
        int receiverIndex = function.managedReceiverIndex.GetValueOrDefault();
        EmitPlaceholderComment(writer, module, 2);
        writer.Append("        public unsafe ").Append(function.returnType.managedName).Append(' ').Append(function.managedName).Append('(');
        bool first = true;
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index == receiverIndex)
                continue;
            if (!first)
                writer.Append(", ");
            first = false;
            BindingParameter parameter = function.parameters[index];
            writer.Append(parameter.type.managedName).Append(' ').Append(parameter.managedName);
        }

        writer.AppendLine(")");
        writer.AppendLine("        {");
        writer.Append("            fixed (").Append(function.managedReceiverType).AppendLine("* pThis = &this)");
        writer.AppendLine("            {");
        writer.Append("                ");
        if (!string.Equals(function.returnType.managedName, "void", StringComparison.Ordinal))
            writer.Append("return ");
        writer.Append(module.name).Append('.').Append(GetRawManagedName(function)).Append("Native(");
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            writer.Append(index == receiverIndex ? "pThis" : function.parameters[index].managedName);
        }

        writer.AppendLine(");");
        writer.AppendLine("            }");
        writer.AppendLine("        }");
    }

    private static void EmitPointerHandles(
        StringBuilder writer,
        BindingModule module
    ) {
        if (!module.wrapPointersAsHandle)
            return;
        IReadOnlyList<PointerHandleSpec> specs = GetPointerHandleSpecs(module);
        foreach (PointerHandleSpec spec in specs)
        {
            writer.AppendLine("    [DebuggerDisplay(\"{DebuggerDisplay,nq}\")] ");
            writer.Append("    public unsafe struct ").Append(spec.wrapperName).Append(" : IEquatable<").Append(spec.wrapperName).AppendLine(">");
            writer.AppendLine("    {");
            writer.Append("        public ").Append(spec.wrapperName).Append('(').Append(spec.pointerType).AppendLine(" handle) { Handle = handle; }");
            writer.Append("        public ").Append(spec.pointerType).AppendLine(" Handle;");
            writer.AppendLine("        public bool IsNull => Handle == null;");
            writer.Append("        public static ").Append(spec.wrapperName).Append(" Null => new ").Append(spec.wrapperName).AppendLine("(null);");
            writer.Append("        public ").Append(spec.pointerType[..^1]).AppendLine(" this[int index]");
            writer.AppendLine("        {");
            writer.AppendLine("            get => Handle[index];");
            writer.AppendLine("            set => Handle[index] = value;");
            writer.AppendLine("        }");
            writer.Append("        public static implicit operator ").Append(spec.wrapperName).Append('(').Append(spec.pointerType).Append(" handle) => new ").Append(spec.wrapperName).AppendLine("(handle);");
            writer.Append("        public static implicit operator ").Append(spec.pointerType).Append('(').Append(spec.wrapperName).AppendLine(" handle) => handle.Handle;");
            writer.Append("        public static bool operator ==(").Append(spec.wrapperName).Append(" left, ").Append(spec.wrapperName).AppendLine(" right) => left.Handle == right.Handle;");
            writer.Append("        public static bool operator !=(").Append(spec.wrapperName).Append(" left, ").Append(spec.wrapperName).AppendLine(" right) => left.Handle != right.Handle;");
            writer.Append("        public bool Equals(").Append(spec.wrapperName).AppendLine(" other) => Handle == other.Handle;");
            writer.Append("        public override bool Equals(object? obj) => obj is ").Append(spec.wrapperName).AppendLine(" other && Equals(other);");
            writer.AppendLine("        public override int GetHashCode() => ((nuint)Handle).GetHashCode();");
            writer.Append("        private string DebuggerDisplay => string.Format(\"").Append(spec.wrapperName).AppendLine(" [0x{0}]\", ((nuint)Handle).ToString(\"X\"));");
            if (spec.depth == 1)
            {
                EmitPointerHandleProperties(writer, spec, specs);
                EmitPointerHandleMemberFunctions(writer, module, spec, specs);
            }

            writer.AppendLine("    }");
            writer.AppendLine();
        }
    }

    private static void EmitPointerHandleProperties(
        StringBuilder writer,
        PointerHandleSpec spec,
        IReadOnlyList<PointerHandleSpec> specs
    ) {
        foreach (BindingField field in spec.type.fields)
        {
            string fieldManagedType = spec.type.nestedTypes.Any(nested => string.Equals(nested.managedName, field.type.managedName, StringComparison.Ordinal)) ? spec.type.managedName + "." + field.type.managedName : field.type.managedName;
            int count = field.arrayDimensions.Count == 0 ? 1 : field.arrayDimensions.Aggregate(1, (
                value,
                dimension
            ) => dimension <= 0 ? 0 : checked(value * dimension));
            if (field.arrayDimensions.Count > 0)
            {
                string spanType = GetSpanElementType(fieldManagedType);
                if (count == 0)
                {
                    writer.Append("        public Span<").Append(spanType).Append("> ").Append(field.managedName).Append("(int length) => new((void*)((byte*)Handle + ").Append(field.offset).AppendLine("), length);");
                }
                else
                {
                    string backingField = count > 1 ? field.managedName + "_0" : field.managedName;
                    writer.Append("        public Span<").Append(spanType).Append("> ").Append(field.managedName).Append(" => new((void*)&Handle->").Append(backingField).Append(", ").Append(count).AppendLine(");");
                }

                continue;
            }

            if (field.isBitField)
            {
                writer.Append("        public ").Append(fieldManagedType).Append(' ').Append(field.managedName).Append(" { get => Handle->").Append(field.managedName).Append("; set => Handle->").Append(field.managedName).AppendLine(" = value; }");
                continue;
            }

            PointerHandleSpec? wrappedField = specs.FirstOrDefault(candidate => string.Equals(candidate.pointerType, field.type.managedName, StringComparison.Ordinal));
            if (IsNativeBool(field.type))
            {
                writer.Append("        public bool ").Append(field.managedName).Append(" { get => Handle->").Append(field.managedName).Append(" != 0; set => Handle->").Append(field.managedName).Append(" = value ? (").Append(fieldManagedType).Append(")1 : (").Append(fieldManagedType).AppendLine(")0; }");
            }
            else if (wrappedField != null)
            {
                writer.Append("        public ref ").Append(wrappedField.wrapperName).Append(' ').Append(field.managedName).Append(" => ref Unsafe.AsRef<").Append(wrappedField.wrapperName).Append(">(&Handle->").Append(field.managedName).AppendLine(");");
            }
            else if (fieldManagedType.Contains('*', StringComparison.Ordinal))
            {
                writer.Append("        public ").Append(fieldManagedType).Append(' ').Append(field.managedName).Append(" { get => Handle->").Append(field.managedName).Append("; set => Handle->").Append(field.managedName).AppendLine(" = value; }");
            }
            else
            {
                writer.Append("        public ref ").Append(fieldManagedType).Append(' ').Append(field.managedName).Append(" => ref Unsafe.AsRef<").Append(fieldManagedType).Append(">(&Handle->").Append(field.managedName).AppendLine(");");
            }
        }
    }

    private static void EmitPointerHandleMemberFunctions(
        StringBuilder writer,
        BindingModule module,
        PointerHandleSpec spec,
        IReadOnlyList<PointerHandleSpec> specs
    ) {
        var members = module.functions.Where(candidate => candidate.kind == BindingFunctionKind.Free && candidate.managedKind == BindingManagedFunctionKind.Instance && !candidate.suppressFriendlySurface && string.Equals(candidate.managedReceiverType, spec.type.managedName, StringComparison.Ordinal)).Select(function =>
        {
            int receiverIndex = function.managedReceiverIndex.GetValueOrDefault();
            FriendlyFunctionPlan plan = CreatePointerHandleFriendlyPlan(CreateFriendlyPlan(function), specs, function);
            FriendlyParameterPlan? receiver = plan.parameters.FirstOrDefault(parameter => ReferenceEquals(parameter.parameter, function.parameters[receiverIndex]));
            return (Function: function, Plan: plan, Receiver: receiver);
        }).Where(member => member.Receiver != null).ToArray();
        HashSet<string> emittedSignatures = new(StringComparer.Ordinal);
        foreach (var member in members)
            emittedSignatures.Add(BuildPointerHandleMemberSignatureKey(member.Function, member.Plan, member.Receiver!, null));
        foreach (var member in members)
        {
            BindingFunction function = member.Function;
            FriendlyFunctionPlan plan = member.Plan;
            FriendlyParameterPlan receiver = member.Receiver!;
            writer.AppendLine();
            EmitPlaceholderComment(writer, module, 2);
            EmitPointerHandleMemberSignature(writer, function, plan, receiver, null);
            writer.AppendLine("        {");
            EmitPointerHandleMemberInvocation(writer, module, function, plan, receiver, null);
            writer.AppendLine("        }");
            foreach (IReadOnlySet<int> omitted in EnumerateDefaultOmissionSets(function, plan))
            {
                string signature = BuildPointerHandleMemberSignatureKey(function, plan, receiver, omitted);
                if (!emittedSignatures.Add(signature))
                    continue;
                writer.AppendLine();
                EmitPlaceholderComment(writer, module, 2);
                EmitPointerHandleMemberSignature(writer, function, plan, receiver, omitted);
                writer.AppendLine("        {");
                EmitPointerHandleMemberInvocation(writer, module, function, plan, receiver, omitted);
                writer.AppendLine("        }");
            }
        }
    }

    private static void EmitPointerHandleMemberSignature(
        StringBuilder writer,
        BindingFunction function,
        FriendlyFunctionPlan plan,
        FriendlyParameterPlan receiver,
        IReadOnlySet<int>? omitted
    ) {
        writer.Append("        public ").Append(GetFriendlyReturnType(function, plan)).Append(' ').Append(function.managedName).Append('(');
        bool first = true;
        foreach (FriendlyParameterPlan parameter in plan.parameters)
        {
            if (ReferenceEquals(parameter, receiver) || omitted?.Contains(function.parameters.IndexOf(parameter.parameter)) == true)
                continue;
            if (!first)
                writer.Append(", ");
            first = false;
            if (parameter.kind == FriendlyParameterKind.Out)
                writer.Append("out ");
            else if (parameter.kind is FriendlyParameterKind.Ref or FriendlyParameterKind.RefBool)
                writer.Append("ref ");
            writer.Append(parameter.managedType).Append(' ').Append(parameter.parameter.managedName);
        }

        writer.AppendLine(")");
    }

    private static void EmitPointerHandleMemberInvocation(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        FriendlyFunctionPlan plan,
        FriendlyParameterPlan receiver,
        IReadOnlySet<int>? omitted
    ) {
        writer.Append("            ");
        if (!string.Equals(GetFriendlyReturnType(function, plan), "void", StringComparison.Ordinal))
            writer.Append("return ");
        writer.Append(module.name).Append('.').Append(function.managedName).Append('(');
        bool first = true;
        foreach (FriendlyParameterPlan parameter in plan.parameters)
        {
            if (!first)
                writer.Append(", ");
            first = false;
            if (ReferenceEquals(parameter, receiver))
            {
                writer.Append("this");
                continue;
            }

            if (omitted?.Contains(function.parameters.IndexOf(parameter.parameter)) == true)
            {
                writer.Append(FormatFriendlyDefault(parameter));
                continue;
            }

            if (parameter.kind == FriendlyParameterKind.Out)
                writer.Append("out ");
            else if (parameter.kind is FriendlyParameterKind.Ref or FriendlyParameterKind.RefBool)
                writer.Append("ref ");
            writer.Append(parameter.parameter.managedName);
        }

        writer.AppendLine(");");
    }

    private static string BuildPointerHandleMemberSignatureKey(
        BindingFunction function,
        FriendlyFunctionPlan plan,
        FriendlyParameterPlan receiver,
        IReadOnlySet<int>? omitted
    ) {
        StringBuilder key = new(function.managedName);
        foreach (FriendlyParameterPlan parameter in plan.parameters)
        {
            if (ReferenceEquals(parameter, receiver) || omitted?.Contains(function.parameters.IndexOf(parameter.parameter)) == true)
                continue;
            key.Append('|').Append(parameter.kind switch
            {
                FriendlyParameterKind.Out => "out ",
                FriendlyParameterKind.Ref or FriendlyParameterKind.RefBool => "ref ",
                _ => string.Empty
            }).Append(NormalizeSignatureType(parameter.managedType));
        }

        return key.ToString();
    }

    private static string NormalizeSignatureType(string managedType) => managedType.EndsWith("?", StringComparison.Ordinal) ? managedType[..^1] : managedType;
    private static string GetSpanElementType(string managedType)
    {
        if (!managedType.Contains('*', StringComparison.Ordinal))
            return managedType;
        string element = managedType.TrimEnd('*').TrimEnd();
        return managedType.Count(character => character == '*') == 1 && !string.Equals(element, "void", StringComparison.Ordinal) ? $"Pointer<{element}>" : "nint";
    }

    private static IReadOnlyList<PointerHandleSpec> GetPointerHandleSpecs(BindingModule module)
    {
        Dictionary<string, BindingType> wrappableTypes = EnumerateTypes(module.types).Where(type => type.kind is BindingTypeKind.Structure or BindingTypeKind.Union && !type.isOpaqueStorage).GroupBy(type => type.managedName, StringComparer.Ordinal).ToDictionary(group => group.Key, group => group.First(), StringComparer.Ordinal);
        Dictionary<string, PointerHandleSpec> specs = new(StringComparer.Ordinal);
        void Add(BindingTypeReference reference)
        {
            string managedName = reference.managedName.Trim();
            int depth = managedName.Reverse().TakeWhile(character => character == '*').Count();
            if (depth == 0)
                return;
            string baseType = managedName[..^depth].TrimEnd();
            if (!wrappableTypes.TryGetValue(baseType, out BindingType? type))
                return;
            string pointerType = baseType + new string('*', depth);
            specs.TryAdd(pointerType, new(type, depth, baseType + string.Concat(Enumerable.Repeat("Ptr", depth)), pointerType));
        }

        foreach (BindingFunction function in module.functions)
        {
            Add(function.returnType);
            foreach (BindingParameter parameter in function.parameters)
                Add(parameter.type);
        }

        foreach (BindingType type in EnumerateTypes(module.types))
        {
            foreach (BindingField field in type.fields)
                Add(field.type);
        }

        return specs.Values.OrderBy(spec => spec.wrapperName, StringComparer.Ordinal).ToArray();
    }

    private static bool HasPointerHandleUsage(
        BindingModule module,
        BindingFunction function
    ) {
        IReadOnlyList<PointerHandleSpec> specs = GetPointerHandleSpecs(module);
        return specs.Any(spec => string.Equals(spec.pointerType, function.returnType.managedName, StringComparison.Ordinal)) || function.parameters.Any(parameter => specs.Any(spec => string.Equals(spec.pointerType, parameter.type.managedName, StringComparison.Ordinal)));
    }

    private static void EmitPointerHandleManagedFunctions(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        string nativeOwner,
        IReadOnlyList<PointerHandleSpec> specs,
        bool suppressRawHandle
    ) {
        PointerHandleSpec? returnSpec = specs.FirstOrDefault(candidate => string.Equals(candidate.pointerType, function.returnType.managedName, StringComparison.Ordinal));
        if (!suppressRawHandle)
        {
            writer.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            writer.Append("        public static ").Append(returnSpec?.wrapperName ?? function.returnType.managedName).Append(' ').Append(function.managedName).Append('(');
            for (int index = 0; index < function.parameters.Count; index++)
            {
                if (index > 0)
                    writer.Append(", ");
                BindingParameter parameter = function.parameters[index];
                PointerHandleSpec? spec = specs.FirstOrDefault(candidate => string.Equals(candidate.pointerType, parameter.type.managedName, StringComparison.Ordinal));
                if (function.managedKind == BindingManagedFunctionKind.Extension && function.managedReceiverIndex == index)
                    writer.Append("this ");
                writer.Append(spec?.wrapperName ?? parameter.type.managedName).Append(' ').Append(parameter.managedName);
            }

            writer.AppendLine(")");
            writer.AppendLine("        {");
            EmitNativeInvocation(writer, function, nativeOwner, 3, parameter =>
            {
                PointerHandleSpec? spec = specs.FirstOrDefault(candidate => string.Equals(candidate.pointerType, parameter.type.managedName, StringComparison.Ordinal));
                return spec == null ? parameter.managedName : parameter.managedName + ".Handle";
            }, returnSpec?.wrapperName);
            writer.AppendLine("        }");
        }

        List<BindingParameter> pointerParameters = function.parameters.Where(parameter => specs.Any(spec => string.Equals(spec.pointerType, parameter.type.managedName, StringComparison.Ordinal))).ToList();
        if (pointerParameters.Count == 0 || pointerParameters.Any(parameter => specs.Any(spec => spec.depth != 1 && string.Equals(spec.pointerType, parameter.type.managedName, StringComparison.Ordinal))))
            return;
        if (!suppressRawHandle)
            writer.AppendLine();
        writer.AppendLine("        [MethodImpl(MethodImplOptions.AggressiveInlining)]");
        bool friendlyBoolReturn = IsNativeBool(function.returnType);
        writer.Append("        public static ").Append(friendlyBoolReturn ? "bool" : function.returnType.managedName).Append(' ').Append(function.managedName).Append('(');
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            BindingParameter parameter = function.parameters[index];
            PointerHandleSpec? spec = specs.FirstOrDefault(candidate => string.Equals(candidate.pointerType, parameter.type.managedName, StringComparison.Ordinal));
            if (spec != null)
                writer.Append("ref ").Append(spec.type.managedName);
            else
                writer.Append(parameter.type.managedName);
            writer.Append(' ').Append(parameter.managedName);
        }

        writer.AppendLine(")");
        writer.AppendLine("        {");
        List<BindingParameter> fixedParameters = pointerParameters;
        int indent = 3;
        foreach (BindingParameter parameter in fixedParameters)
        {
            AppendIndent(writer, indent);
            writer.Append("fixed (").Append(parameter.type.managedName).Append(' ').Append(GetTemporaryName(parameter)).Append(" = &").Append(parameter.managedName).AppendLine(")");
            AppendIndent(writer, indent);
            writer.AppendLine("{");
            indent++;
        }

        EmitNativeInvocation(writer, function, nativeOwner, indent, parameter => fixedParameters.Contains(parameter) ? GetTemporaryName(parameter) : parameter.managedName, convertBool: friendlyBoolReturn);
        for (int index = fixedParameters.Count - 1; index >= 0; index--)
        {
            indent--;
            AppendIndent(writer, indent);
            writer.AppendLine("}");
        }

        writer.AppendLine("        }");
    }

    private static FriendlyFunctionPlan CreatePointerHandleFriendlyPlan(
        FriendlyFunctionPlan plan,
        IReadOnlyList<PointerHandleSpec> specs,
        BindingFunction function
    ) {
        int receiverIndex = function.managedKind == BindingManagedFunctionKind.Instance ? function.managedReceiverIndex.GetValueOrDefault(-1) : -1;
        BindingParameter? receiverParameter = receiverIndex >= 0 && receiverIndex < function.parameters.Count ? function.parameters[receiverIndex] : null;
        FriendlyParameterPlan? originalReceiver = plan.parameters.FirstOrDefault(parameter => ReferenceEquals(parameter.parameter, receiverParameter));
        List<FriendlyParameterPlan> parameters = plan.parameters.Select(parameter =>
        {
            PointerHandleSpec? spec = specs.FirstOrDefault(candidate => string.Equals(candidate.pointerType, parameter.parameter.type.managedName, StringComparison.Ordinal));
            bool isReceiver = ReferenceEquals(parameter.parameter, receiverParameter);
            return spec == null || parameter.kind == FriendlyParameterKind.Span && !isReceiver ? parameter : parameter with
            {
                kind = FriendlyParameterKind.PointerHandle,
                managedType = spec.wrapperName,
                elementType = spec.type.managedName
            };
        }).ToList();
        HashSet<string> hiddenLengths = new(plan.hiddenLengths, StringComparer.Ordinal);
        if (originalReceiver?.kind == FriendlyParameterKind.Span && !string.IsNullOrWhiteSpace(originalReceiver.parameter.marshalling.lengthParameter))
        {
            string lengthName = originalReceiver.parameter.marshalling.lengthParameter!;
            BindingParameter? lengthParameter = function.parameters.FirstOrDefault(parameter => string.Equals(parameter.nativeName, lengthName, StringComparison.Ordinal) || string.Equals(parameter.managedName, lengthName, StringComparison.Ordinal));
            if (lengthParameter != null && parameters.All(parameter => !ReferenceEquals(parameter.parameter, lengthParameter)))
                parameters.Add(new(lengthParameter, FriendlyParameterKind.Raw, lengthParameter.type.managedName, null));
            hiddenLengths.Remove(lengthName);
            if (lengthParameter != null)
            {
                hiddenLengths.Remove(lengthParameter.nativeName);
                hiddenLengths.Remove(lengthParameter.managedName);
            }
        }

        parameters.Sort((
            left,
            right
        ) => function.parameters.IndexOf(left.parameter).CompareTo(function.parameters.IndexOf(right.parameter)));
        PointerHandleSpec? returnSpec = specs.FirstOrDefault(candidate => string.Equals(candidate.pointerType, function.returnType.managedName, StringComparison.Ordinal));
        return new(parameters, hiddenLengths, plan.returnsString, plan.returnsBool, returnSpec?.wrapperName);
    }

    private static void EmitCallbackManagedFunction(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        string nativeOwner
    ) {
        List<(BindingParameter Parameter, BindingDelegate Delegate, int Index)> callbacks = [];
        for (int index = 0; index < function.parameters.Count; index++)
        {
            BindingParameter parameter = function.parameters[index];
            if (parameter.marshalling.strategy != MarshallingStrategy.Callback || (string.Equals(parameter.type.managedName, "void*", StringComparison.Ordinal) && (parameter.marshalling.callbackLifetime == BindingCallbackLifetime.Unspecified || parameter.marshalling.callbackThreading == BindingCallbackThreading.Unspecified)))
                continue;
            BindingDelegate? bindingDelegate = module.delegates.FirstOrDefault(candidate => string.Equals(candidate.nativeName, parameter.type.nativeName, StringComparison.Ordinal));
            if (bindingDelegate != null)
                callbacks.Add((parameter, bindingDelegate, index));
        }

        if (callbacks.Count == 0)
            return;
        writer.AppendLine();
        if (module.autoWrapCallbacks)
        {
            foreach ((BindingParameter parameter, BindingDelegate bindingDelegate, int index) in callbacks)
            {
                string slot = BuildCallbackSlotName(function, parameter, index);
                writer.Append("        private static NativeCallback<").Append(bindingDelegate.managedName).Append("> __autoWrappedCallback_").Append(slot).AppendLine(";");
                writer.Append("        private static ").Append(bindingDelegate.managedName).Append("? __AutoWrapCallback_").Append(slot).Append('(').Append(bindingDelegate.managedName).AppendLine("? callback)");
                writer.AppendLine("        {");
                writer.Append("            if (__autoWrappedCallback_").Append(slot).AppendLine(".isAllocated) __autoWrappedCallback_" + slot + ".Dispose();");
                writer.AppendLine("            if (callback is null)");
                writer.AppendLine("            {");
                writer.Append("                __autoWrappedCallback_").Append(slot).AppendLine(" = default;");
                writer.AppendLine("                return null;");
                writer.AppendLine("            }");
                writer.Append("            __autoWrappedCallback_").Append(slot).Append(" = new NativeCallback<").Append(bindingDelegate.managedName).AppendLine(">(callback);");
                writer.Append("            return __autoWrappedCallback_").Append(slot).AppendLine(".callback;");
                writer.AppendLine("        }");
            }

            writer.AppendLine();
        }

        writer.Append("        public static ").Append(function.returnType.managedName).Append(' ').Append(function.managedName).Append('(');
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            BindingParameter parameter = function.parameters[index];
            (BindingParameter Parameter, BindingDelegate Delegate, int Index)? callback = callbacks.Cast<(BindingParameter, BindingDelegate, int)?>().FirstOrDefault(candidate => candidate?.Item3 == index);
            if (callback is { } match)
            {
                string name = module.autoWrapCallbacks && callbacks.Count == 1 ? "callback" : parameter.managedName;
                writer.Append(match.Delegate.managedName);
                if (module.autoWrapCallbacks)
                    writer.Append('?');
                writer.Append(' ').Append(name);
            }
            else
            {
                writer.Append(parameter.type.managedName).Append(' ').Append(parameter.managedName);
            }
        }

        writer.AppendLine(")");
        writer.AppendLine("        {");
        EmitNativeInvocation(writer, function, nativeOwner, 3, parameter =>
        {
            (BindingParameter Parameter, BindingDelegate Delegate, int Index)? callback = callbacks.Cast<(BindingParameter, BindingDelegate, int)?>().FirstOrDefault(candidate => ReferenceEquals(candidate?.Item1, parameter));
            if (callback is not { } match)
                return parameter.managedName;
            string argumentName = module.autoWrapCallbacks && callbacks.Count == 1 ? "callback" : parameter.managedName;
            string delegateExpression = module.autoWrapCallbacks ? $"__AutoWrapCallback_{BuildCallbackSlotName(function, parameter, match.Index)}({argumentName})" : argumentName;
            return $"({parameter.type.managedName})Utils.GetFunctionPointerForDelegate({delegateExpression})";
        }, keepAlive: callbacks.Select(callback => module.autoWrapCallbacks && callbacks.Count == 1 ? "callback" : callback.Parameter.managedName).ToArray());
        writer.AppendLine("        }");
    }

    private static string BuildCallbackSlotName(
        BindingFunction function,
        BindingParameter parameter,
        int index
    ) => SanitizeIdentifier(function.managedName) + "_" + SanitizeIdentifier(parameter.managedName) + "_" + index;
    private static string SanitizeIdentifier(string value)
    {
        StringBuilder result = new(value.Length);
        foreach (char character in value)
            result.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
        return result.ToString();
    }

    private static void EmitAdditionalPointerOverloads(
        StringBuilder writer,
        BindingModule module,
        BindingFunction function,
        string nativeOwner
    ) {
        if (!module.generateAdditionalOverloads || function.managedKind != BindingManagedFunctionKind.Static)
            return;
        for (int pointerIndex = 0; pointerIndex < function.parameters.Count; pointerIndex++)
        {
            BindingParameter pointer = function.parameters[pointerIndex];
            string? elementType = GetPointerElementType(pointer.type);
            if (pointer.type.pointerDepth != 1 || pointer.direction != BindingDirection.In || elementType is not ("byte" or "sbyte") || !string.IsNullOrWhiteSpace(pointer.marshalling.lengthParameter))
                continue;
            writer.AppendLine();
            EmitSinglePointerOverload(writer, function, nativeOwner, pointerIndex, $"ReadOnlySpan<{elementType}>", false);
            if (!module.varyingTypes.Contains("nint", StringComparer.Ordinal))
            {
                writer.AppendLine();
                EmitSinglePointerOverload(writer, function, nativeOwner, pointerIndex, "in " + elementType, true);
            }
        }
    }

    private static void EmitSinglePointerOverload(
        StringBuilder writer,
        BindingFunction function,
        string nativeOwner,
        int pointerIndex,
        string publicType,
        bool byReference
    ) {
        writer.Append("        public static ").Append(function.returnType.managedName).Append(' ').Append(function.managedName).Append('(');
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            BindingParameter parameter = function.parameters[index];
            writer.Append(index == pointerIndex ? publicType : parameter.type.managedName).Append(' ').Append(parameter.managedName);
        }

        writer.AppendLine(")");
        writer.AppendLine("        {");
        BindingParameter pointer = function.parameters[pointerIndex];
        writer.Append("            fixed (").Append(pointer.type.managedName).Append(' ').Append(GetTemporaryName(pointer)).Append(" = ");
        if (byReference)
            writer.Append('&');
        writer.Append(pointer.managedName).AppendLine(")");
        writer.AppendLine("            {");
        EmitNativeInvocation(writer, function, nativeOwner, 4, parameter => ReferenceEquals(parameter, pointer) ? GetTemporaryName(pointer) : parameter.managedName);
        writer.AppendLine("            }");
        writer.AppendLine("        }");
    }

    private static void EmitNativeInvocation(
        StringBuilder writer,
        BindingFunction function,
        string nativeOwner,
        int indent,
        Func<BindingParameter, string> getArgument,
        string? returnWrapper = null,
        bool convertBool = false,
        IReadOnlyList<string>? keepAlive = null
    ) {
        AppendIndent(writer, indent);
        if (!string.Equals(function.returnType.managedName, "void", StringComparison.Ordinal))
            writer.Append(function.returnType.managedName).Append(" ret = ");
        writer.Append(nativeOwner).Append(GetRawManagedName(function)).Append("Native(");
        for (int index = 0; index < function.parameters.Count; index++)
        {
            if (index > 0)
                writer.Append(", ");
            writer.Append(getArgument(function.parameters[index]));
        }

        writer.AppendLine(");");
        if (keepAlive != null)
        {
            foreach (string argument in keepAlive)
            {
                AppendIndent(writer, indent);
                writer.Append("global::System.GC.KeepAlive(").Append(argument).AppendLine(");");
            }
        }

        if (!string.Equals(function.returnType.managedName, "void", StringComparison.Ordinal))
        {
            AppendIndent(writer, indent);
            if (convertBool)
                writer.AppendLine("return ret != 0;");
            else if (returnWrapper == null)
                writer.AppendLine("return ret;");
            else
                writer.Append("return new ").Append(returnWrapper).AppendLine("(ret);");
        }
    }

